/**
 * Общие правила для сверки норм расходников (bench/spec_norms.js — проекты,
 * bench/norm_ours.js — наши сметы): по какому слову название раздела относится
 * к системе и по каким словам строка — к категории расходника. Чтобы обе стороны
 * считались одинаково, правила лежат в одном месте.
 */
const lc = s => String(s || '').toLowerCase().replace(/ё/g, 'е');

// Система — по названию раздела (спецификации проекта или раздела нашей сметы).
const SYSTEMS = [
    ['тёплый пол', s => /напольн|тепл\S*\s+пол/.test(s)],
    ['канализация', s => /канализ/.test(s)],
    ['водоснабжение', s => /водоснаб|хвс|гвс|водопровод/.test(s)],
    ['котельная', s => /котельн|котел|принципиальн|обвязк|теплоснабж/.test(s)],
    ['радиаторы', s => /отоплен|радиатор|приборы/.test(s)],
];
const systemOf = section => { const s = lc(section); const h = SYSTEMS.find(([, f]) => f(s)); return h ? h[0] : null; };

// Категории; первая подошедшая. isMeters(row) — труба и изоляция считаются метрами.
const CATS = [
    ['труба', r => /(^|[^а-я])труб/.test(lc(r.name)) && !/хомут|держател|кронштейн|подвес|раструб|канализ|гофр|дренаж|воздуховод|уплотн|антилед|коаксиал|дымоход|наконечник|защит|кожух|трубк|евроконус|концов|фитинг/.test(lc(r.name))],
    ['изоляция, м', r => /теплоизоляц|изоляц|energoflex|энергофлекс|armaflex|k-flex|вспененн|трубка/.test(lc(r.name)) && !/насосн|групп|бак\b|котел|кожух\s+для|лента/.test(lc(r.name))],
    ['хомуты и опоры', r => /хомут|опор[аы]\s+для|кронштейн|подвес|держател|скоба|скобы|крепл/.test(lc(r.name)) && !/шпильк|дюбел/.test(lc(r.name))],
    ['шпильки, дюбели', r => /шпильк|дюбел|анкер|шуруп|саморез/.test(lc(r.name))],
    ['угольники, отводы', r => /угольник|отвод|уголок|колено/.test(lc(r.name)) && !/коаксиал|дымоход|антилед/.test(lc(r.name))],
    ['тройники', r => /тройник|крестовин/.test(lc(r.name))],
    ['муфты, переходы', r => /муфт|переходник|переход\b|вставк|футорк|ниппел|сгон|американк|соединител/.test(lc(r.name))],
    ['заглушки', r => /заглушк|пробк/.test(lc(r.name))],
    ['краны, клапаны', r => /кран|клапан|вентил|задвижк/.test(lc(r.name))],
    ['лента, лён, паста', r => /лента|лен\b|л[её]н|паста|нить|герметик|фум|скотч/.test(lc(r.name))],
];
const catOf = r => { const h = CATS.find(([, f]) => f(r)); return h ? h[0] : null; };

// Метры по названию позиции каталога: «(100 м)», «штанга 4 м», «бухта 200 м». Иначе — как есть.
const metersOf = (name, q, desc, unit) => {
    // Позиция в метрах (отрезается по длине) — количество и есть метры.
    if (/^(м|пог\.?\s?м)$/i.test(String(unit || '').trim())) return q;
    // Длина бухты у позиций вроде «Труба 16x2.2 в теплоизоляции» — в описании: «бухт (по 100 м)».
    const d = desc && String(desc).match(/бухт\S*\s*\(?по\s*(\d+)\s*м/i);
    if (d) return q * parseInt(d[1], 10);
    const m = String(name).match(/\((\d+(?:[.,]\d+)?)\s*м\)/i) || String(name).match(/(?:штанг\S*|бухт\S*)\s*(\d+(?:[.,]\d+)?)\s*м/i)
        || String(name).match(/(\d+(?:[.,]\d+)?)\s*м\b\s*$/i);
    return m ? q * parseFloat(m[1].replace(',', '.')) : q;
};

module.exports = { lc, SYSTEMS, systemOf, CATS, catOf, metersOf };
