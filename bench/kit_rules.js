/**
 * Проверка правил комплектности (RecognizeMatch.suggest, KIT_RULES) на небольших
 * рукописных сметах: что предложит блок «Возможно, не хватает», а о чём промолчит.
 * Каждый случай — ожидаемый набор причин; расхождение печатается красным словом
 * «РАСХОЖДЕНИЕ» и даёт ненулевой код выхода.
 *
 * Запуск (из корня worktree):
 *   node bench/kit_rules.js
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const sb = { console, document: { createElement: () => ({ style: {} }) }, window: {}, navigator: { userAgent: 'node' },
    localStorage: { getItem: () => null, setItem: () => {} }, module: undefined };
sb.globalThis = sb;
vm.createContext(sb);
vm.runInContext(fs.readFileSync(path.join(root, 'catalog.js'), 'utf8') + '\n;\n' +
    fs.readFileSync(path.join(root, 'recognize_match.js'), 'utf8') + '\n;\nglobalThis.__RM = RecognizeMatch;\n', sb);
const RM = sb.__RM;

const row = (raw, type, qty, extra) => Object.assign({ raw, type: type || '', qty: qty || 1, unit: 'шт' }, extra || {});
const BOILER = row('Котёл газовый настенный Baxi Eco 24 кВт', 'котёл');
const CASES = [
    // [название, строки, причины, которые ДОЛЖНЫ быть, причины, которых НЕ должно быть]
    ['котёл один', [BOILER], ['Котёл без предохранительного клапана', 'Котёл без манометра', 'Котёл без фильтра на системе'], []],
    ['котёл + клапан + манометр + фильтр', [BOILER, row('Клапан предохранительный 3 бар 1/2"'), row('Манометр 6 бар 1/4"'), row('Фильтр сетчатый косой 3/4"')],
        [], ['Котёл без предохранительного клапана', 'Котёл без манометра', 'Котёл без фильтра на системе']],
    ['котёл + группа безопасности', [BOILER, row('Группа безопасности котла 3 бар')], [], ['Котёл без предохранительного клапана']],
    ['котёл + шламоотделитель', [BOILER, row('Фильтр-шламоотделитель магнитный 3/4"')], [], ['Котёл без фильтра на системе']],
    ['только обвязка котла — самого котла нет', [row('Комплект подключения котла'), row('Группа безопасности котла'), row('Кран шаровой для котла 3/4"')],
        [], ['Котёл без предохранительного клапана', 'Котёл без манометра', 'Котёл без фильтра на системе']],
    ['котельная как слово', [row('Рама котельной несущая'), row('Расширительный бак котельной 18 л')],
        [], ['Котёл без предохранительного клапана', 'Котёл без манометра', 'Котёл без фильтра на системе']],
    ['котёл «с насосом» и «с бойлером» остаётся котлом', [row('Котёл газовый двухконтурный с встроенным насосом и бойлером 24 кВт')], ['Котёл без предохранительного клапана'], []],
    ['электрокотёл', [row('Электрокотёл Zota 12 кВт')], ['Котёл без предохранительного клапана', 'Котёл без манометра'], []],
    ['бак «для котла» — не котёл', [row('Расширительный бак для котла 18 л')], [], ['Котёл без предохранительного клапана', 'Котёл без манометра']],
    ['радиаторы без котла', [row('Радиатор стальной 22 500х1000', 'радиатор', 4)], [], ['Котёл без предохранительного клапана']],
];

let bad = 0;
for (const [name, rows, want, notWant] of CASES) {
    const got = RM.suggest(rows, null).map(s => s.reason);
    const missing = want.filter(w => !got.some(g => g === w));
    const extra = notWant.filter(w => got.some(g => g === w));
    const ok = !missing.length && !extra.length;
    if (!ok) bad++;
    console.log(`${ok ? 'ok ' : 'РАСХОЖДЕНИЕ'}  ${name}` + (ok ? '' : `  — нет: ${missing.join('; ') || '—'} | лишнее: ${extra.join('; ') || '—'}`));
    if (process.argv.includes('-v')) got.forEach(g => console.log('        · ' + g));
}
console.log(bad ? `\n${bad} расхождений` : '\nвсе случаи сошлись');
process.exitCode = bad ? 1 : 0;
