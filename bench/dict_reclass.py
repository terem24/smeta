OURS = [(re.compile(rx, re.I), name, lvl) for rx, name, lvl in OURS]


def cls(key):
    for rx, name, lvl in OURS:
        if rx.search(key):
            return name, lvl
    return None, 'нет'


fam = {}
unk = []
for r in rows:
    k, n = r['лист'], int(r['проектов'])
    name, lvl = cls(k)
    if lvl == 'есть':
        fam[name] = max(fam.get(name, 0), n)
    elif lvl == 'нет' and name:
        fam[('НЕТ', name)] = max(fam.get(('НЕТ', name), 0), n)
    elif lvl == 'нет':
        unk.append((k, n))

print('ЧТО У НАС ЕСТЬ — максимум по любому варианту названия, % проектов (нижняя оценка):')
for name, n in sorted(((k, v) for k, v in fam.items() if isinstance(k, str)), key=lambda t: -t[1]):
    print('  %3d%%  %s' % (round(100 * n / SETS), name))
print()
print('ЧЕГО У НАС НЕТ (подтверждено):')
