-- Приглашения от менеджеров магазинов, часть 1 из 2: колонки.
--
-- Розничные магазины подключаются как карточки дистрибьюторов: у каждой уже есть
-- промокод и почта менеджера. Здесь добавляются две вещи, которых не хватало:
--   • лимит приглашений у компании — сколько монтажников менеджер может привязать
--     своим промокодом. Само число привязанных не хранится, оно считается по
--     users.distributor_id, поэтому лимит меняется одной цифрой в карточке;
--   • отметка времени регистрации у пользователя — по ней сайт отличает новые
--     учётки (им нужен промокод) от старых (их правило не касается).
--
-- ПОЧЕМУ У СТАРЫХ КОМПАНИЙ ЛИМИТ 999. Промокоды нынешних дистрибьюторов раздаются
-- давно и без счёта. Оставь им 5 — в день выкладки их промокоды перестали бы
-- работать. Магазинам лимит 5 выставляется при создании карточки.
--
-- ПОЧЕМУ registered_at У СТАРЫХ ПУСТОЕ. Колонка добавляется без значения по
-- умолчанию и только потом получает default now(): иначе Postgres проставил бы
-- «сейчас» всем существующим строкам, и все старые монтажники в один день стали
-- бы «новыми» — с требованием промокода при входе.
--
-- Выполнить вручную в Supabase SQL Editor, весь файл целиком за один раз.
-- Часть 2 (функции проверки кода и привязки) — отдельным файлом.

alter table public.distributors
    add column if not exists invite_limit integer not null default 5;

update public.distributors set invite_limit = 999;

comment on column public.distributors.invite_limit is
    'Сколько монтажников можно привязать промокодом этой компании. '
    'Занято = число users с этим distributor_id и обычным тарифом.';

alter table public.users
    add column if not exists registered_at timestamptz;

alter table public.users
    alter column registered_at set default now();

comment on column public.users.registered_at is
    'Когда создана учётка. Пусто у зарегистрированных до 11.09.2026 — '
    'к ним требование промокода при входе не применяется.';
