-- Разовая уборка: одна сфера деятельности на человека.
--
-- Монтаж и продажу совмещать нельзя (решение владельца 11.09.2026). В форме
-- анкеты сферы давно переключаются радиокнопками — обе сразу там не выбрать,
-- так что новых таких записей не появится. Но от прежней версии, где стояли
-- галочки, осталось двое с обеими сферами:
--
--   Крупа Михаил Иванович        e0840a7b-88ce-4999-a471-09977a196f8e
--   Свириденко Андрей Петрович   19f930dd-c5ee-4ee2-9f63-ebfc8feab432
--
-- Оставляем им монтаж, продажу снимаем.
--
-- Побочный эффект в панели управления: разбивка в карточках перестанет
-- двоиться. Было «монтажниками 34 · продавцами 27» при 56 сметах (пять смет
-- этих двоих считались в обоих числах), станет 34 и 22 — ровно 56.
--
-- Запускать в SQL Editor консоли Supabase. Повторный запуск безопасен:
-- условие «есть обе сферы» второй раз никого не найдёт.

-- 1. Кто попадёт под правку (ожидается 2 строки).
select id, username, email, account_type, activity_types
  from users
 where activity_types @> array['Монтажник']::text[]
   and activity_types @> array['Продавец']::text[];

-- 2. Сама правка.
update users
   set activity_types = array['Монтажник']::text[]
 where activity_types @> array['Монтажник']::text[]
   and activity_types @> array['Продавец']::text[];

-- 3. Проверка: должно вернуть 0.
select count(*)
  from users
 where activity_types @> array['Монтажник']::text[]
   and activity_types @> array['Продавец']::text[];
