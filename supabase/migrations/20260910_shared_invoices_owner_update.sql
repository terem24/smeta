-- Монтажник переотправляет клиенту ту же смету: разрешаем обновлять свои строки
-- в shared_invoices.
--
-- Что было не так. Номер ссылки хранится в смете и переиспользуется, чтобы адрес,
-- отправленный клиенту, не менялся. Поэтому при ПОВТОРНОЙ отправке одной и той же
-- сметы upsert идёт уже не вставкой, а обновлением — и база отвечает:
--   [42501] new row violates row-level security policy (USING expression)
--           for table "shared_invoices"
-- Проверено 09.09.2026 на живом сайте: обновление отбивается даже у того, кто сам
-- создал строку минуту назад. Права на обновление у роли authenticated нет вообще,
-- есть только вставка (её добавляли ради страницы invoice.html, работающей от anon).
-- То есть повторная отправка любой сметы у любого монтажника всегда шла мимо базы,
-- и клиенту уходила длинная офлайн-ссылка вместо короткой (11 таких случаев в
-- админке за 30 дней, у одного монтажника 8 раз подряд с 20.08 по 07.09.2026).
--
-- Клиентская часть уже починена (app.js 7.37): после отказа смета пишется заново под
-- новым номером, ссылка остаётся короткой. Но адрес при этом каждый раз меняется, и
-- клиент, открывший вчерашнюю ссылку, видит вчерашний вариант сметы. Эта миграция
-- убирает и вторую половину: строка обновляется на месте, ссылка перестаёт меняться,
-- а повтор с новым номером остаётся страховкой на настоящие аварийные случаи.
--
-- Почему только свои строки. Право знать чужой номер ссылки — это право ОТВЕТИТЬ на
-- смету (согласовать, прислать замечания), и для этого есть отдельная функция
-- set_shared_invoice_status из 20260816_shared_invoice_status_rpc.sql, которая меняет
-- ровно три поля. Открывать по этому же номеру перезапись состава и цен нельзя.
--
-- with check той же строкой, что и using: иначе владелец смог бы переписать user_id и
-- подарить свою смету другому аккаунту (или отвязать её от себя, сделав ничейной).
--
-- Старые строки, у которых user_id пустой или записан от прежнего способа входа,
-- эта политика не покрывает — намеренно: разрешение обновлять ничейные строки означало
-- бы, что любой вошедший может переписать чужую смету, зная только номер ссылки. Такие
-- сметы один раз переедут на новый номер (страховкой из app.js) и дальше будут вести
-- себя нормально: новая строка создаётся уже с правильным владельцем.
--
-- Выполнить вручную в Supabase SQL Editor (весь файл целиком, за один раз).

-- 1. Табличное право. Само по себе доступа к строкам не даёт — их отбирает политика ниже.
grant update on public.shared_invoices to authenticated;

-- 2. Политика. Пересоздаём, чтобы файл можно было выполнить повторно без ошибки.
drop policy if exists "Владелец обновляет свою смету" on public.shared_invoices;

create policy "Владелец обновляет свою смету"
    on public.shared_invoices
    for update
    to authenticated
    using (user_id = auth.uid())
    with check (user_id = auth.uid());

-- 3. Что получилось. Ожидаем в списке строку с cmd = UPDATE, permissive = PERMISSIVE и
--    qual = (user_id = auth.uid()).
--
--    Если рядом окажется ЕЩЁ ОДНА политика на UPDATE с permissive = RESTRICTIVE — она
--    продолжит запрещать обновление независимо от нашей: ограничивающие политики
--    складываются через И, а не через ИЛИ. В этом случае пришлите вывод этого запроса,
--    разберёмся с ней отдельно.
select policyname, cmd, permissive, roles, qual, with_check
  from pg_policies
 where schemaname = 'public'
   and tablename  = 'shared_invoices'
 order by cmd, policyname;
