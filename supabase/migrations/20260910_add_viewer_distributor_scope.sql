-- Область видимости наблюдателя: список компаний, чьи данные ему показывать.
--
-- До этого «Наблюдатель» видел всю платформу целиком — всех монтажников, все
-- сметы, всю переписку. Роль же заводилась под конкретную задачу: смотреть за
-- своими дистрибьюторами. Компаний у одного наблюдателя может быть несколько,
-- поэтому это массив, а не одно поле distributor_id (оно у монтажника значит
-- «мой менеджер», у менеджера — «моя компания», и занимать его третьим смыслом
-- нельзя).
--
-- Пустой массив означает «не назначено ни одной компании»: тогда наблюдатель
-- не видит ничего. Это правильнее, чем показать ему всех подряд.
--
-- Выполнить вручную в Supabase SQL Editor.

alter table public.users
    add column if not exists viewer_distributor_ids uuid[] not null default '{}';
