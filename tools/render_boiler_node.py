# -*- coding: utf-8 -*-
"""
Кадр «Котёл с обвязкой» для листа котельной (раздел 2.1 сметы): настенный газовый котёл Haier
NeoSlim 1.18/1.24 Ti (одноконтурный, встроенный трёхходовой клапан) и его обвязка — ровно то,
что кладёт смета в 2.1 на этот котёл.

    blender --background --python tools/render_boiler_node.py -- <папка> <вариант>
      вариант — haier1

Сборка по резьбам (концы — assembly_check: котёл НР 3/4"; кран SVB-0004 ВР/НР; американка
SFT-0041 ВР/НР; сепаратор RFW-0070 ВР/ВР; фильтр RFW-0080 вход НР, выход накидная гайка;
переходники нерж. RSS-1021 ВПр-НР и RSS-1022 ВПр-ВР 22x3/4"):
  подача (A):   котёл НР — кран (ВР сверху, НР снизу) — американка (ВР/НР) — сепаратор (ВР/ВР) —
                переходник ВПр-НР 22x3/4" — труба нерж. 22 вниз;
  на бойлер (I): котёл НР — американка (ВР/НР) — переходник ВПр-ВР 22x3/4" — труба 22 вниз;
  обратка (G):  котёл НР — кран (ВР/НР) — накидная гайка соединителя фильтра — фильтр (корпус
                вертикально) — вход НР со встроенным краном — переходник ВПр-ВР 22x3/4" — труба 22;
  газ (C) и подпитка (D) — патрубки котла; газовая подводка и кран в смету не входят (газовая служба).
Источники:
  * котёл — руководство Haier NeoSlim Ti, стр. 28 (A 725, B 400, C 240; патрубки снизу слева
    направо через 65/72/53/75 мм, крайние — 59 от левого и 75 от правого края; ось патрубков
    D 81 от стены; ось дымохода F 136 от стены; G 200 между отверстиями планки), стр. 29
    (1.18/1.24 Ti: A подача, I выход на бойлер, C газ, D ХВС, E предохр. клапан, F слив, G обратка);
    фото каталога: белый корпус, логотип вверху, чёрная панель индикации внизу.
  * сепаратор RFW-0070-259520 — паспорт ROMMER, табл. 4: H 175, H1 94, L 80,5, L1 51, D 62;
    «поворотный» — корпус вертикально и на вертикальной трубе.
  * фильтр RFW-0080 3/4" — паспорт ROMMER, табл. 4: D 73, L 142, L1 72, H 192, H1 138; п. 5.3:
    на обратке, корпус вертикально, установка в любом положении (соединитель поворотный).
  * кран SVB-0004-200020 — паспорт STOUT SVB (ручка «бабочка», чёрная — фото); американка
    SFT-0041 — фото; переходники RSS — фото (нерж., красное кольцо пресс-фитинга).
  * дымоход — комплект коаксиальный 60/100 (SCR-6010): колено 90° от котла в стену.
  * стабилизатор ST 250 (SST-0001-000250) — фото: серый корпус с индикатором, на стене рядом.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from blender_parts import *  # noqa: F401,F403
from mathutils import Vector, Matrix
import bpy

_argv = sys.argv[sys.argv.index('--') + 1:]
OUT, VAR = _argv[0], _argv[1]
TAG = 'boiler_' + VAR

add_colors({
    'bwhite': (0.95, 0.95, 0.95),
    'bpanel': (0.10, 0.11, 0.13),
    'bscreen': (0.90, 0.92, 0.95),
    'logo': (0.20, 0.22, 0.26),
    'redring': (0.85, 0.15, 0.13),
    'filterblk': (0.13, 0.13, 0.14),
    'stabgrey': (0.86, 0.87, 0.88),
    'flue': (0.94, 0.94, 0.94),
    'alu': (0.80, 0.81, 0.83),
})

W, H, D = 0.400, 0.725, 0.240     # котёл (руководство, стр. 28)
YW = 0.0                          # плоскость стены; котёл перед ней (−Y)
YP = YW - 0.081                   # ось патрубков
XP = {'A': 0.059, 'I': 0.124, 'C': 0.196, 'D': 0.249, 'G': 0.325}
ZB = 0.0                          # низ корпуса котла
ANCH = {}
TOP = Matrix.Rotation(-math.pi / 2, 4, 'Y')       # детали «по оси X» -> по оси Z (вверх)


def boiler():
    part('mf')
    m = mat('bwhite', rough=0.40, coat=0.3)
    yc = YW - D / 2
    box('корпус котла', (W, D - 0.004, H - 0.050), m, (W / 2, yc, ZB + 0.050 + (H - 0.050) / 2))
    # нижняя часть корпуса чуть утоплена (панель патрубков)
    box('низ корпуса', (W - 0.030, D - 0.040, 0.048), mat('stabgrey', rough=0.5), (W / 2, yc + 0.012, ZB + 0.025))
    # панель индикации (фото): чёрный прямоугольник внизу по центру с белым экраном
    box('панель индикации', (0.130, 0.004, 0.115), mat('bpanel', rough=0.3, coat=0.6), (W / 2, YW - D - 0.001, ZB + 0.120))
    box('экран', (0.050, 0.002, 0.022), mat('bscreen', rough=0.4), (W / 2, YW - D - 0.003, ZB + 0.150))
    # логотип — тёмная полоска вверху
    box('логотип', (0.060, 0.002, 0.012), mat('logo', rough=0.5), (W / 2, YW - D - 0.001, ZB + H - 0.075))
    marks['mf'] = (W / 2, YW - D, ZB + H * 0.55)
    # патрубки снизу: НР 3/4" (газ и подпитка — тоже, газовая подводка не в смете)
    for k, x in XP.items():
        r = 0.0128 if k != 'D' else 0.0104
        lathe('патрубок ' + k, [(r * 0.9, 0), (r * 0.9, 0.006)] + thread(r, 0.014, start=0.006), M_NICKEL(),
              (x, YP, ZB), '-Z', segs=32)
    # сброс предохранительного клапана и слив — тонкие трубки
    for x in (0.272, 0.290):
        lathe('сброс', [(0.004, 0), (0.004, 0.020)], M_NICKEL(), (x, YP + 0.020, ZB), '-Z', segs=16)
    return ZB - 0.020                 # низ резьбы патрубков


def chimney():
    """Коаксиальный дымоход 60/100: патрубок вверх из котла, колено 90° и труба в стену."""
    part('head')
    w = mat('flue', rough=0.35, coat=0.2)
    xc, yc, z0 = W / 2, YW - 0.136, ZB + H
    lathe('адаптер дымохода', [(0.050, 0), (0.050, 0.060), (0.052, 0.062), (0.052, 0.075)], w, (xc, yc, z0), 'Z', segs=48)
    R = 0.075
    arc = [(xc, yc + R - R * math.cos(t), z0 + 0.075 + R * math.sin(t)) for t in [k * math.pi / 2 / 16 for k in range(17)]]
    tube('колено дымохода', [(xc, yc, z0 + 0.070)] + arc + [(xc, YW + 0.02, z0 + 0.075 + R)], 0.050, w)
    lathe('манжета', [(0.054, 0), (0.054, 0.010)], mat('alu', rough=0.4, metal=0.5), (xc, YW - 0.012, z0 + 0.075 + R), 'Y', segs=48)
    marks['head'] = (xc, yc + R * 0.4, z0 + 0.075 + R * 0.9)


def stabilizer():
    """Стабилизатор ST 250 на стене слева от котла (фото: серый корпус, решётка сверху, индикатор)."""
    part('stab')
    m = mat('stabgrey', rough=0.45, coat=0.2)
    x, z = -0.150, ZB + 0.420
    box('стабилизатор', (0.150, 0.095, 0.120), m, (x, YW - 0.050, z))
    box('индикатор', (0.050, 0.002, 0.018), mat('bpanel', rough=0.3), (x, YW - 0.098, z - 0.010))
    for k in range(6):
        box('решётка', (0.004, 0.060, 0.002), mat('logo', rough=0.5), (x - 0.030 + k * 0.012, YW - 0.050, z + 0.061))
    tube('шнур', [(x + 0.075, YW - 0.050, z - 0.040), (x + 0.110, YW - 0.050, z - 0.040),
                  (0.040, YW - 0.050, ZB + 0.200)], 0.0028, mat('stabgrey', rough=0.5))
    marks['stab'] = (x, YW - 0.098, z + 0.030)


def ball_valve(x, z, col='black'):
    """Кран шаровой SVB-0004 3/4" ВР/НР с бабочкой (вертикально): сверху шестигранник ВР
    на патрубок, корпус с поясками, снизу НР. Возвращает низ резьбы НР."""
    ni = M_NICKEL()
    part('ek')
    hexnut('кран ВР', 0.031, 0.013, ni, (x, YP, z), '-Z')
    lathe('корпус крана', [(0.0150, 0), (0.0172, 0.003), (0.0178, 0.010), (0.0178, 0.020), (0.0165, 0.026)],
          ni, (x, YP, z - 0.013), '-Z', sharp=40)
    zc = z - 0.013 - 0.013
    T = Matrix.Translation(Vector((x, YP, zc))) @ TOP
    valve_boss(T)
    transformed(T, butterfly, 0, 0, col)
    hexnut('кран шестигранник НР', 0.028, 0.006, ni, (x, YP, z - 0.039), '-Z')
    lathe('кран НР', thread(0.0128, 0.013), ni, (x, YP, z - 0.045), '-Z', segs=40)
    marks['ek'] = (x, YP - 0.030, zc + 0.010)
    return z - 0.058


def union(x, z):
    """Американка SFT-0041 3/4" ВР/НР (фото): шестигранник ВР, большая накидная гайка, НР."""
    ni = M_NICKEL()
    part('feed')
    hexnut('американка ВР', 0.032, 0.014, ni, (x, YP, z + 0.010), '-Z')
    hexnut('американка гайка', 0.040, 0.016, ni, (x, YP, z - 0.004), '-Z', ch=0.12)
    lathe('американка НР', [(0.0135, 0), (0.0135, 0.004)] + thread(0.0128, 0.012, start=0.004), ni, (x, YP, z - 0.020), '-Z', segs=40)
    marks['feed'] = (x, YP - 0.020, z - 0.010)
    return z - 0.036


def separator(x, z):
    """Сепаратор RFW-0070 3/4" (паспорт: H 175, H1 94, L 80,5, L1 51, D 62): проточная часть ВР/ВР
    по оси трубы, корпус D 62 вертикально, смещён на L1 к зрителю, сверху автоматический
    воздухоотводчик. Латунь. Возвращает низ проточной части (ВР)."""
    br = M_BRASS()
    part('mount')
    L = 0.0805
    zc = z - L / 2
    lathe('проточная часть', [(0.0170, 0), (0.0170, L)], br, (x, YP, z), '-Z', segs=40)
    for zz in (z, z - L + 0.012):
        hexnut('сепаратор ВР', 0.032, 0.012, br, (x, YP, zz), '-Z')
    yb = YP - 0.051
    box('перемычка', (0.026, 0.040, 0.030), br, (x, (YP + yb) / 2, zc))
    lathe('корпус сепаратора', [(0.0, -0.094), (0.026, -0.094), (0.031, -0.088), (0.031, 0.040), (0.026, 0.046), (0.012, 0.050)],
          br, (x, yb, zc), 'Z', segs=48, sharp=40)
    lathe('воздухоотводчик', [(0.012, 0), (0.014, 0.004), (0.014, 0.026), (0.009, 0.030), (0.0, 0.031)],
          br, (x, yb, zc + 0.050), 'Z', segs=32)
    lathe('слив', [(0.007, 0), (0.007, 0.012)], br, (x, yb, zc - 0.094), '-Z', segs=20)
    marks['mount'] = (x, yb - 0.031, zc + 0.020)
    return z - L


def adapter(x, z, fem, axis='-Z', y=None):
    """Переходник нерж. RSS-1021 (ВПр-НР) или RSS-1022 (ВПр-ВР) 22x3/4" (фото): резьбовой конец,
    шестигранник, раструб под пресс с красным кольцом. Возвращает конец раструба (начало трубы)."""
    y = YP if y is None else y
    part('tube')
    st = M_SATIN()
    d = {'-Z': Vector((0, 0, -1)), 'X': Vector((1, 0, 0))}[axis]
    p = Vector((x, y, z))
    if fem:
        hexnut('переходник ВР', 0.032, 0.016, st, tuple(p), axis)
        p = p + d * 0.016
    else:
        lathe('переходник НР', thread(0.0128, 0.012), st, tuple(p), axis, segs=40)
        p = p + d * 0.012
        hexnut('переходник шестигранник', 0.027, 0.007, st, tuple(p), axis)
        p = p + d * 0.007
    lathe('раструб', [(0.0118, 0), (0.0150, 0.004), (0.0150, 0.022), (0.0130, 0.026)], st, tuple(p), axis, segs=40)
    lathe('кольцо пресс', [(0.0152, 0), (0.0152, 0.005)], mat('redring', rough=0.4), tuple(p + d * 0.008), axis, segs=40)
    return p + d * 0.024


def pipe(pts):
    part('tube')
    tube('труба нерж. 22', [tuple(p) for p in pts], 0.011, M_SATIN())


def mag_filter(x, z):
    """Магнитный фильтр RFW-0080 3/4" на обратке (паспорт: D 73, L 142, L1 72, H 192, H1 138):
    накидная гайка соединителя вверх на НР крана, колено соединителя в корпус; корпус чёрный
    вертикально, смещён вправо на L1; вход НР со встроенным краном (красная бабочка) — вправо."""
    br = M_BRASS()
    part('end')
    hexnut('гайка соединителя', 0.032, 0.012, br, (x, YP, z + 0.010), '-Z')
    lathe('соединитель', [(0.0130, 0), (0.0130, 0.020)], br, (x, YP, z - 0.002), '-Z', segs=32)
    zc = z - 0.040                         # ось входа/выхода корпуса
    xb = x + 0.072
    tube('колено соединителя', [(x, YP, z - 0.020), (x, YP, zc + 0.012), (x + 0.012, YP, zc), (xb - 0.030, YP, zc)], 0.0130, br)
    blk = mat('filterblk', rough=0.45, coat=0.3)
    lathe('корпус фильтра', [(0.0, -0.138 + 0.040), (0.033, -0.138 + 0.040), (0.0365, -0.090), (0.0365, 0.030),
                             (0.033, 0.048), (0.020, 0.054)], blk, (xb, YP, zc), 'Z', segs=56, sharp=40)
    lathe('кольцо', [(0.0368, 0), (0.0368, 0.016)], mat('redring', rough=0.4), (xb, YP, zc - 0.010), 'Z', segs=56)
    lathe('пробка воздухоотводчика', [(0.010, 0), (0.010, 0.012), (0.0, 0.013)], br, (xb, YP, zc + 0.054), 'Z', segs=24)
    lathe('сливной кран', [(0.008, 0), (0.008, 0.014)], br, (xb, YP, zc - 0.098), '-Z', segs=20)
    # вход: латунный патрубок с краном (красная бабочка) — вправо
    xi = xb + 0.036
    lathe('вход фильтра', [(0.0160, 0), (0.0160, 0.026)], br, (xi, YP, zc), 'X', segs=40)
    T = Matrix.Translation(Vector((xi + 0.013, YP, zc)))
    valve_boss(T)
    transformed(T, butterfly, 0, 0, 'flagred')
    lathe('вход НР', thread(0.0128, 0.012), br, (xi + 0.026, YP, zc), 'X', segs=40)
    marks['end'] = (xb, YP - 0.037, zc + 0.010)
    return (xi + 0.038, zc)


def build():
    sc = reset()
    part('')
    g = mat('bwhite', rough=0.6, alpha=0.18)
    ob = box('стена', (1.10, 0.004, 1.50), g, (0.15, YW + 0.002, ZB + 0.15))
    ob.modifiers.clear()
    for c in list(ob.users_collection):
        c.objects.unlink(ob)
    coll('sheath').objects.link(ob)
    z0 = boiler()
    chimney()
    stabilizer()
    ZE = ZB - 0.42                          # низ отрезков труб на кадре (дальше — к гидравлике)
    # подача A
    x = XP['A']
    z = ball_valve(x, z0)
    z = union(x, z + 0.012)
    z = separator(x, z + 0.010)
    p = adapter(x, z + 0.012, fem=False)
    pipe([p + Vector((0, 0, 0.004)), (x, YP, ZE)])
    ANCH['tube:a'] = (x, YP, (p.z + ZE) / 2)
    # на бойлер I
    x = XP['I']
    z = union(x, z0)
    p = adapter(x, z + 0.012, fem=True)
    pipe([p + Vector((0, 0, 0.004)), (x, YP, ZE)])
    # обратка G
    x = XP['G']
    z = ball_valve(x, z0)
    xi, zc = mag_filter(x, z + 0.012)
    p = adapter(xi, zc, fem=True, axis='X')
    R = 0.045
    arc = [(p.x + R * math.sin(t), YP, zc - R + R * math.cos(t)) for t in [k * math.pi / 2 / 10 for k in range(1, 11)]]
    pipe([p + Vector((-0.004, 0, 0)), (p.x, YP, zc)] + arc + [(p.x + R, YP, ZE)])
    return sc


def main():
    sc = build()
    cam = camera(sc, objects=list(coll('solid').objects))
    zones, pts, proj = frame_meta(sc, cam, ANCH)
    sheath = list(coll('sheath').objects)
    for o in sheath:
        o.hide_render = True
    sc.render.film_transparent = True
    freestyle(sc, 'solid', LINE_COLOR, 1.8)
    render(sc, os.path.join(OUT, TAG + '_solid.png'))
    for o in sheath:
        o.hide_render = False
    for o in coll('solid').objects:
        o.is_holdout = True
    freestyle(sc, 'sheath', (0.62, 0.64, 0.68), 1.0)
    eng = sc.render.engine
    set_engine(sc, 'eevee')
    render(sc, os.path.join(OUT, TAG + '_sheath.png'))
    sc.render.engine = eng
    for o in sheath:
        o.hide_render = True
    ID = {'mf': (1, 0, 0), 'ek': (0, 1, 0), 'tube': (0, 0, 1), 'mount': (1, 1, 0), 'feed': (0, 1, 1),
          'end': (1, 0, 1), 'head': (1, 1, 1), 'stab': (1, 1, 1)}
    id_pass(sc, list(coll('solid').objects), ID, os.path.join(OUT, TAG + '_id.png'))
    write_meta(sc, os.path.join(OUT, TAG + '.json'), zones, pts, proj)


main()
