def parts_sheet():
    """Детали по отдельности, крупно, в ряд — для сверки с фото (вариант parts)."""
    sc = reset()
    x = 0.0
    ball_valve((x, YP, 0.10)); x += 0.10
    union((x, YP, 0.10)); x += 0.10
    separator((x, YP, 0.12), side=1); x += 0.19
    mag_filter((x + 0.06, YP, 0.12), side=1); x += 0.25
