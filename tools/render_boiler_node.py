def three_way(c, side=1):
    """Комплект трёхходового клапана BX4991100069 (паспорт BAXI «Клапан трёхходовой ГВС», ред. 31-08-2023, табл. 1:
    вход AB G3/4 ВР, выходы A — в отопление и B — в змеевик бойлера G3/4 НР; фото каталога: латунный корпус-тройник,
    чёрный привод сбоку, кабель): AB сверху (ВР на НР крана), A вниз, B вбок (side), привод к зрителю.
    Возвращает (конец A, конец B)."""
    br = M_BRASS()
    part('kit')
    c = Vector(c)
    hexnut('клапан AB ВР', 0.032, 0.014, br, tuple(c), '-Z')
    zc = c.z - 0.034
    lathe('корпус клапана', [(0.0, 0), (0.019, 0), (0.021, 0.004), (0.021, 0.034), (0.019, 0.038), (0.0, 0.038)], br,
          (c.x, c.y, c.z - 0.014), '-Z', segs=48)
    a = Vector((c.x, c.y, c.z - 0.052))
    lathe('выход A НР', [(0.0150, 0), (0.0150, 0.004)] + thread(0.0128, 0.012, start=0.004), br, tuple(a), '-Z', segs=40)
    b = Vector((c.x + side * 0.021, c.y, zc))
    ax = 'X' if side > 0 else '-X'
    lathe('выход B НР', [(0.0150, 0), (0.0150, 0.008)] + thread(0.0128, 0.012, start=0.008), br, tuple(b), ax, segs=40)
    # привод: чёрный корпус с крышкой на латунной шейке, к зрителю (−Y)
