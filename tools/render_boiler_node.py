    stab600(sx, sz)
    part('head')
    # шнур к вводу кабелей котла (рис. 2, поз. 19/22: низ котла слева спереди) — по стене за трубами, под котлом вперёд
    tube('шнур к котлу', [(sx + 0.040, YW - 0.020, sz), (sx + 0.040, YW - 0.020, ZB - 0.014), (0.150, YW - 0.020, ZB - 0.014),
                          (0.150, YW - 0.225, ZB - 0.014), (0.150, YW - 0.225, ZB)],
         0.0028, mat('bwhite', rough=0.5))
    tube('шнур в сеть', [(sx - 0.040, YW - 0.040, sz), (sx - 0.040, YW - 0.040, ZE + 0.05)], 0.0028, mat('bwhite', rough=0.5))
    # подача
    x = XP['S']
    p = union((x, YP, z0))
    p = ball_valve(p + Vector((0, 0, 0.012)))
    a, b = three_way(p + Vector((0, 0, 0.012)), side=1)
    p = adapter(a, fem=True)
    zsep = p.z - 0.110
    top = adapter((x, YP, zsep - 0.012), fem=False, ax='Z')
    pipe([p + Vector((0, 0, 0.004)), top + Vector((0, 0, -0.004))])
    q = separator((x, YP, zsep), side=-1)
    p = adapter(q + Vector((0, 0, 0.012)), fem=False)
