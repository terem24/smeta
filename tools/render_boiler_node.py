    x = XP['R']
    p = union((x, YP, z0))
    p = ball_valve(p + Vector((0, 0, 0.012)))
    p, ax = mag_filter(p + Vector((0, 0, 0.012)), side=-1)
    p = adapter(p + Vector((0.012, 0, 0)), fem=True, ax=ax)
