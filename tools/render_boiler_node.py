def boiler(ox=0.0):
    """Корпус: скруглённые вертикальные кромки фасада (контур в плане — прямоугольник со
    скруглениями), плоский низ, из него патрубки; чёрная стеклянная панель с индикатором внизу
    фасада; логотип вверху; сверху патрубок дымохода."""
    part('mf')
    m = mat('bwhite', rough=0.35, coat=0.4)
    plan = rounded([(0.0, YW - D), (W, YW - D), (W, YW - 0.004), (0.0, YW - 0.004)], 0.022, seg=6)
    plan = [(x + ox, y) for x, y in plan]
    prism('корпус котла', plan, H, m, Matrix.Translation(Vector((0, 0, ZB + H / 2))), bevel=0.004)   # prism — симметрично по толщине
    # панель индикации (фото GE0Q6QE0CRU, масштаб по ширине 400): чёрное стекло 198x157, низ в 31 мм от
    # низа корпуса; крупные цифры температуры по центру, ряд из трёх значков и ряд кнопок ниже; логотип
    # Haier тёмным текстом 69 мм шириной в 69 мм от верха
    zp = ZB + 0.031 + 0.0785
    box('панель индикации', (0.198, 0.003, 0.157), mat('bpanel', rough=0.12, coat=0.9), (ox + W / 2, YW - D - 0.0015, zp))
    box('линия', (0.150, 0.001, 0.0012), mat('bscreen', rough=0.3), (ox + W / 2, YW - D - 0.0035, zp + 0.064))
    box('цифры', (0.040, 0.001, 0.024), mat('bscreen', rough=0.3), (ox + W / 2, YW - D - 0.0035, zp + 0.025))
    for k in range(3):
        box('значок', (0.008, 0.001, 0.008), mat('bscreen', rough=0.3), (ox + W / 2 - 0.028 + k * 0.028, YW - D - 0.0035, zp - 0.012))
        box('кнопка', (0.007, 0.001, 0.0015), mat('bscreen', rough=0.3), (ox + W / 2 - 0.028 + k * 0.028, YW - D - 0.0035, zp - 0.042))
    box('логотип', (0.069, 0.001, 0.011), mat('logo', rough=0.5), (ox + W / 2, YW - D - 0.0012, ZB + H - 0.069))
    marks['mf'] = (ox + W / 2, YW - D, ZB + H * 0.55)
    # патрубки снизу (НР 3/4", ХВС 1/2")
    for k, x in XP.items():
        r = 0.0128 if k != 'D' else 0.0104
        lathe('патрубок ' + k, [(r * 0.85, 0), (r * 0.85, 0.006)] + thread(r, 0.014, start=0.006), M_NICKEL(),
              (ox + x, YP, ZB), '-Z', segs=32)
    # сброс предохранительного клапана (E) и слив (F) — короткие латунные штуцеры
    for x in (0.272, 0.290):
        lathe('штуцер', [(0.0045, 0), (0.0045, 0.016)], M_BRASS(), (ox + x, YP + 0.030, ZB), '-Z', segs=16)
    return ZB - 0.020


def chimney():
    """Коаксиальный дымоход 60/100: адаптер вверх из котла, колено 90° и труба в стену."""
    part('head')
    w = mat('flue', rough=0.35, coat=0.2)
    xc, yc, z0 = W / 2, YW - 0.136, ZB + H
    lathe('адаптер дымохода', [(0.050, 0), (0.050, 0.060), (0.053, 0.062), (0.053, 0.078)], w, (xc, yc, z0), 'Z', segs=48)
    R = 0.075
    arc = [(xc, yc + R - R * math.cos(t), z0 + 0.075 + R * math.sin(t)) for t in [k * math.pi / 2 / 16 for k in range(17)]]
    tube('колено дымохода', [(xc, yc, z0 + 0.070)] + arc + [(xc, YW + 0.02, z0 + 0.075 + R)], 0.050, w)
    lathe('манжета', [(0.054, 0), (0.054, 0.010)], mat('alu', rough=0.4, metal=0.5), (xc, YW - 0.012, z0 + 0.075 + R), 'Y', segs=48)
    marks['head'] = (xc, yc + R * 0.4, z0 + 0.075 + R * 0.9)


