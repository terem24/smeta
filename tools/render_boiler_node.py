def photo_poly(name, path, pts, w, h, loc, mtx):
    """Плоская наклейка по контуру pts (в мм-долях, начало — левый низ, размер w x h): текстура ложится на всю фигуру,
    а контур (скругления) — её собственный, без прямоугольной рамки по краю."""
    import bmesh
    bm = bmesh.new()
    uvl = bm.loops.layers.uv.new('UVMap')
    c0 = bm.verts.new((0, 0, 0))
    vs = [bm.verts.new((u - w / 2, v - h / 2, 0)) for u, v in pts]
    for i in range(len(vs)):
        f = bm.faces.new((c0, vs[i], vs[(i + 1) % len(vs)]))
        for lp in f.loops:
            if lp.vert is c0:
                lp[uvl].uv = (0.5, 0.5)
            else:
                k = vs.index(lp.vert)
                lp[uvl].uv = (pts[k][0] / w, pts[k][1] / h)
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    me.materials.append(photo_mat(path, rough=0.55, coat=0.05))
    ob = bpy.data.objects.new(name, me)
    ob.matrix_world = Matrix.Translation(Vector(loc)) @ mtx
    return link(ob)


