    hexnut('муфта 2', 0.030, 0.012, g, tuple(c + Vector((0, 0, -0.024))), '-Z')
    p = c + Vector((0, 0, -0.040))
    lathe('кран газ', [(0.0150, 0), (0.0172, 0.004), (0.0172, 0.030), (0.0150, 0.034)], g, tuple(p), '-Z', segs=40)
    box('ручка газ', (0.010, 0.060, 0.006), mat('gasyel', rough=0.4), (p.x, p.y - 0.032, p.z - 0.017))
    tube('газовая труба', [tuple(p + Vector((0, 0, -0.034))), (p.x, p.y, z_end)], 0.0105, mat('gasyel', rough=0.45))


