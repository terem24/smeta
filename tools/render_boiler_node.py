    ANCH['tube:a'] = (x, YP, (p.z + ZE) / 2)
    p = adapter(b, fem=True, ax='X')
    R = 0.040
    arc = [(p.x + R * math.sin(t), YP, p.z - R + R * math.cos(t)) for t in [k * math.pi / 2 / 10 for k in range(1, 11)]]
    pipe([p + Vector((-0.004, 0, 0)), (p.x, YP, p.z)] + arc + [(p.x + R, YP, ZE)])
