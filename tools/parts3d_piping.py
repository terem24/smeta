# -*- coding: utf-8 -*-
"""
Обвязка котельной для tools/export_parts_glb.py: пресс-фитинги из нержавейки 22 мм (угольник 90°, угольник 45°,
тройник), отрезок трубы 22x1,2 и мембранный расширительный бак для отопления 18 л. Не запускается сама:
экспортёр выполняет файл в пространстве имён Blender-библиотеки (lathe, tube, mat, M_SATIN, port, Vector ...).

Откуда внешний вид (фото каталога img/<артикул>.jpg):
  * пресс-фитинги STOUT SSS-2003/2004/2013 — хром, у каждого раструба СИНЕЕ уплотнительное кольцо (в кадрах узлов у
    переходников RSS ROMMER красное — у STOUT синее), на теле «STOUT 22x22»;
  * бак STH-0004-000018 — красный корпус, чёрный колпачок воздушного ниппеля сверху, белая наклейка со знаком STOUT,
    снизу фланец с присоединением G 3/4".
Размеры: у пресс-фитингов 22 мм паспорта STOUT в папке аудита нет — взяты ТИПОВЫЕ (глубина раструба 22, плечо от
оси до среза раструба 40 мм, наружный диаметр тела 25,6) и помечены в src каждого порта. У бака диаметр 250 мм —
карточка продавца (master-water.ru), высота 360 мм — по пропорциям фото, паспорт размеров не даёт.
"""

add_colors({
    'ringblue': (0.12, 0.30, 0.75),
    'tankred': (0.80, 0.10, 0.09),
})

R_BODY, R_RING, R_PIPE = 0.0128, 0.0140, 0.0110
SOCK = 0.022            # глубина раструба
LEG = 0.040             # от оси фитинга до среза раструба
SRC_P = 'типовой пресс-фитинг 22 мм: размер плеча принят, паспорта STOUT на SSS-2003/2004/2013 в папке аудита нет'


def _socket(name, mouth, axis):
    """Раструб: от среза внутрь по оси axis ('-Z', '-X', ...): кромка, синее кольцо и тело."""
    st = M_SATIN()
    lathe(name + ' тело', [(R_BODY, 0.0), (R_BODY, SOCK)], st, mouth, axis, segs=36)
    lathe(name + ' кромка', [(R_BODY * 1.04, 0.0), (R_BODY * 1.04, 0.003)], st, mouth, axis, segs=36)
    lathe(name + ' кольцо', [(R_RING, 0.005), (R_RING, 0.012)], mat('ringblue', rough=0.35), mouth, axis, segs=36)


def _bend(pts):
    tube('тело', pts, R_BODY, M_SATIN())


def elbow90():
    """Угольник 90° ВПр-ВПр 22 (SSS-2003-000022). Начало — срез первого раструба, он смотрит в +Z, второй — в +X."""
    part('mf')
    _socket('раструб 1', (0, 0, 0), '-Z')
    _socket('раструб 2', (LEG, 0, -LEG), '-X')
    r = 0.014
    arc = [(r - r * math.cos(t), 0, -(LEG - r) - r * math.sin(t)) for t in [k * math.pi / 2 / 12 for k in range(13)]]
    _bend([(0, 0, -SOCK + 0.002), (0, 0, -(LEG - r))] + arc[1:] + [(LEG - SOCK + 0.002, 0, -LEG)])
    return [port('a', Vector((0, 0, 0)), (0, 0, 1), 'P', '22', SRC_P),
            port('b', Vector((LEG, 0, -LEG)), (1, 0, 0), 'P', '22', SRC_P)]


def elbow45():
    """Угольник 45° ВПр-НПр 22 (SSS-2004-000022): раструб в +Z и гладкий конец под раструб соседнего фитинга."""
    part('mf')
    _socket('раструб', (0, 0, 0), '-Z')
    d = Vector((math.sin(math.pi / 4), 0, -math.cos(math.pi / 4)))
    c = Vector((0, 0, -LEG))
    end = c + d * 0.045
    _bend([(0, 0, -SOCK + 0.002), tuple(c), tuple(end)])
    tube('гладкий конец', [tuple(c + d * 0.020), tuple(end)], R_PIPE, M_SATIN())
    return [port('a', Vector((0, 0, 0)), (0, 0, 1), 'P', '22', SRC_P),
            port('b', end, tuple(d), 'P', '22', SRC_P + '; гладкий конец НПр')]


def tee22():
    """Тройник равнопроходной ВПр 22 (SSS-2013-000022): проход по оси X, отвод вверх (+Z)."""
    part('mf')
    _socket('раструб лев', (-LEG, 0, 0), 'X')
    _socket('раструб пр', (LEG, 0, 0), '-X')
    _socket('раструб отв', (0, 0, LEG), '-Z')
    _bend([(-LEG + SOCK - 0.002, 0, 0), (LEG - SOCK + 0.002, 0, 0)])
    _bend([(0, 0, 0), (0, 0, LEG - SOCK + 0.002)])
    return [port('a', Vector((-LEG, 0, 0)), (-1, 0, 0), 'P', '22', SRC_P),
            port('b', Vector((LEG, 0, 0)), (1, 0, 0), 'P', '22', SRC_P),
            port('c', Vector((0, 0, LEG)), (0, 0, 1), 'P', '22', SRC_P)]


def pipe22(length=0.250):
    """Отрезок трубы нерж. 22x1,2 (SSS-2001-000022 режется штангой 4 м): оба конца гладкие под раструбы."""
    part('tube')
    tube('труба нерж. 22', [(0, 0, 0), (0, 0, -length)], R_PIPE, M_SATIN())
    src = 'труба нержавеющая 22x1,2, паспорт STOUT SSS-2001; отрезок условной длины %d мм' % round(length * 1000)
    return [port('a', Vector((0, 0, 0)), (0, 0, 1), 'P', '22', src),
            port('b', Vector((0, 0, -length)), (0, 0, -1), 'P', '22', src)]


def expansion_tank_18():
    """Мембранный бак для отопления STH-0004-000018 (18 л, красный, вертикальный): начало — центр низа, присоединение
    G 3/4" НР вниз по оси, воздушный ниппель сверху под чёрным колпачком, наклейка STOUT спереди."""
    D, H = 0.250, 0.360
    R = D / 2
    part('mf')
    red = mat('tankred', rough=0.35, coat=0.6)
    blk = mat('bblack', rough=0.5)
    ni = M_NICKEL()
    z0 = 0.030            # низ бака над торцом присоединения
    prof = [(0.045, z0), (R * 0.82, z0 + 0.004), (R * 0.97, z0 + 0.028), (R, z0 + 0.060), (R, H - 0.060),
            (R * 0.97, H - 0.028), (R * 0.82, H - 0.004), (0.020, H)]
    lathe('корпус бака', prof, red, (0, 0, 0), 'Z', segs=72)
    lathe('шов бака', [(R * 1.004, H * 0.50), (R * 1.004, H * 0.50 + 0.004)], red, (0, 0, 0), 'Z', segs=72)
    lathe('фланец низ', [(0.045, 0.012), (0.045, z0)], ni, (0, 0, 0), 'Z', segs=40)
    lathe('присоединение G3/4', [(0.0125, 0), (0.0125, 0.012)] + thread(0.0132, 0.012, start=0.012), ni, (0, 0, 0.012), '-Z', segs=36)
    lathe('колпачок ниппеля', [(0.014, H - 0.004), (0.014, H + 0.016), (0.011, H + 0.020), (0.001, H + 0.020)], blk, (0, 0, 0), 'Z', segs=32)
    decal('наклейка STOUT', 'stout_plaque.png', 0.100, 0.100 * 0.35, (0, -R - 0.0006, H * 0.50 + 0.015))
    return [port('conn', Vector((0, 0, 0)), (0, 0, -1), 'M', '3/4"',
                 'каталог (conn 3/4"), STH-0004: осевое присоединение; наружная резьба принята; размеры бака: D 250 — продавец, H 360 — по фото')]
