"""
Сборщики бойлера косвенного нагрева STOUT OptiBase (SWH-2110) и насосной группы STOUT SDG-0002
для tools/export_parts_glb.py. Файл не запускается сам: экспортёр читает его исходник и выполняет
в одном пространстве имён с деталями Blender-библиотеки (lathe, box, tube, mat, thread, M_* ...).

Единицы — метры (как в библиотеке), экспортёр показывает миллиметры.
Начало координат: бойлер — центр пола; группа — середина низа в плоскости стены. Лицо — к -Y.

Откуда размеры (папка «Аудит паспортов STOUT-ROMMER»):
  * бойлер — паспорт SWH-2110 (рис. 3-5): диаметр и высота кожуха, высоты патрубков от пола считаны
    с чертежей и точны до ±20 мм (на чертеже цепочки размеров мелкие). Резьбы: G1" НР (вход ХВС,
    теплообменник, рециркуляция), горячая вода G3/4" (150, 200 л) или G1" (от 300 л), ТЭН G1 1/2" ВР.
  * группа — паспорт SDG-0002 ред. 3, табл. 4.2: L 247, H 410, A 212, H1 363, F 125, нижние
    патрубки G 1 1/2" НР, верхние Rp 1" ВР. Шаг верхних патрубков паспорт не даёт — принят F.
    Внешний вид — по фото каталога: чёрный ЕРР-кожух, латунь, два термометра, насос Grundfos.
"""

add_colors({
    'epp': (0.10, 0.10, 0.11),
    'yellowbr': (0.93, 0.74, 0.10),
    'pumpgrey': (0.34, 0.36, 0.39),
    'pumpblue': (0.12, 0.36, 0.72),
    'bred': (0.82, 0.13, 0.11),
    'bblue': (0.13, 0.36, 0.82),
    'bblack': (0.06, 0.06, 0.07),
})


def _stub(name, x, y, z, axis, r_thread, length, m, hexaf=None):
    """Резьбовой штуцер: шестигранник у основания (по желанию) и накатка резьбы на конце."""
    lathe(name, [(r_thread + 0.0012, 0), (r_thread + 0.0012, 0.008)] + thread(r_thread, length, start=0.008),
          m, (x, y, z), axis, segs=32)
    if hexaf:
        hexnut(name + ' шестигранник', hexaf, 0.009, m, (x, y, z), axis)


def swh_boiler(D, H, ports, hot_inch):
    """Бойлер: белый кожух с чёрной верхней крышкой, термометр и логотип спереди, регулируемые ножки,
    патрубки справа (+X) по ports = {имя: (высота от пола, размер, назначение)}, ТЭН-заглушка слева,
    верхний патрубок горячей воды и заглушка анода. Возвращает список портов экспортёра."""
    R, foot = D / 2, 0.040
    part('mf')
    white = mat('bwhite', rough=0.45, coat=0.3)
    blk = mat('bblack', rough=0.55)
    ni = M_NICKEL()
    lathe('кожух', [(0.001, foot), (R * 0.90, foot), (R, foot + 0.035), (R, H - 0.040)], white, (0, 0, 0), 'Z', segs=96)
    lathe('крышка', [(R * 1.001, H - 0.040), (R * 1.001, H - 0.014), (R * 0.97, H - 0.004),
                     (R * 0.80, H), (0.001, H + 0.004)], blk, (0, 0, 0), 'Z', segs=96)
    for k in range(3):
        a = math.radians(90 + 120 * k)
        lathe('ножка', [(0.026, 0), (0.026, foot)], blk, (0.72 * R * math.cos(a), 0.72 * R * math.sin(a), 0), 'Z', segs=24)
    # термометр и логотип спереди, у верха
    zt = H - 0.22
    lathe('термометр рамка', [(0.001, 0), (0.028, 0), (0.028, 0.010), (0.022, 0.012)], blk, (0, -R, zt), '-Y', segs=40)
    lathe('термометр шкала', [(0.001, 0.011), (0.022, 0.011)], mat('bscreen', rough=0.3), (0, -R, zt), '-Y', segs=40)
    box('логотип', (0.072, 0.0012, 0.016), mat('logo', rough=0.5), (0, -R - 0.0004, H - 0.12))
    out = []
    for name, (z, size, role) in ports.items():
        _stub('патрубок ' + name, R - 0.012, 0, z, 'X', 0.0166, 0.024, ni, hexaf=0.040)
        out.append(port(name, Vector((R + 0.024, 0, z)), (1, 0, 0), 'M', size, role))
    # ТЭН: заглушка 1 1/2" слева у низа, как на чертеже (поз. 9, 10)
    lathe('заглушка ТЭН', [(0.0245, 0), (0.0245, 0.026), (0.0215, 0.026)], blk, (-R + 0.012, 0, 0.195), '-X', segs=36)
    out.append(port('heater', Vector((-R - 0.014, 0, 0.195)), (-1, 0, 0), 'F', '1 1/2"', 'паспорт SWH-2110: ТЭН G1 1/2" ВР, поз. 9'))
    # горячая вода: фланцевый патрубок сверху
    r_hot = 0.0166 if hot_inch == '1"' else 0.0132
    _stub('патрубок горячей воды', R * 0.45, 0, H, 'Z', r_hot, 0.026, ni, hexaf=0.036)
    out.append(port('dhw', Vector((R * 0.45, 0, H + 0.034)), (0, 0, 1), 'M', hot_inch, 'паспорт SWH-2110: выход ГВС, НР'))
    hexnut('анод заглушка', 0.050, 0.012, blk, (-R * 0.40, 0, H), 'Z')
    return out


def pump_group_mix25():
    """Насосная группа SDG-0002-002501 (DN25, четырёхходовой клапан, без насоса; с насосом UPSO 25-65/180
    -002502). Показан вариант с насосом: чёрный ЕРР-кожух с нишей, жёлтая латунь, термометры, насос."""
    L, A, H = 0.247, 0.212, 0.410
    part('mf')
    epp = mat('epp', rough=0.92)
    yb = mat('yellowbr', rough=0.35, metal=0.6)
    ni = M_NICKEL()
    dx = 0.0625           # F = 125: шаг нижних патрубков
    yc = -0.100           # ось труб от стены
    # кожух ЕРР: задняя стенка, щёки, дно и верх с карманами термометров
    box('кожух задняя', (L, 0.060, H), epp, (0, -0.030, H / 2))
    for s in (-1, 1):
        box('кожух щека', (0.042, A, H), epp, (s * (L / 2 - 0.021), -A / 2, H / 2))
    box('кожух дно', (L, A, 0.075), epp, (0, -A / 2, 0.0375))
    box('кожух верх', (L, A, 0.085), epp, (0, -A / 2, H - 0.0425))
    # трубы: левая — обратка, правая — подача (насос и клапан)
    tube('труба левая', [(-dx, yc, 0.0), (-dx, yc, H - 0.055)], 0.0145, yb)
    tube('труба правая низ', [(dx, yc, 0.0), (dx, yc, 0.115)], 0.0145, yb)
    tube('труба правая верх', [(dx, yc, 0.295), (dx, yc, H - 0.055)], 0.0145, yb)
    tube('байпас', [(-dx, yc, 0.105), (dx, yc, 0.105)], 0.0115, yb)
    # четырёхходовой термостатический клапан: латунный корпус и красная головка вперёд
    hexnut('клапан корпус', 0.040, 0.034, yb, (dx, yc, 0.088), 'Z')
    lathe('клапан головка', [(0.001, 0), (0.021, 0), (0.021, 0.030), (0.015, 0.034)], mat('bred', rough=0.4),
          (dx, yc - 0.012, 0.105), '-Y', segs=32)
    # насос (UPSO 25-65/180): корпус на трубе по вертикали, моторная головка вперёд
    gr = mat('pumpgrey', rough=0.5, metal=0.3)
    lathe('насос корпус', [(0.040, 0.115), (0.040, 0.295)], gr, (dx, yc, 0.0), 'Z', segs=40)
    hexnut('насос гайка низ', 0.052, 0.014, ni, (dx, yc, 0.112), 'Z')
    hexnut('насос гайка верх', 0.052, 0.014, ni, (dx, yc, 0.285), 'Z')
    lathe('насос моторная головка', [(0.001, 0), (0.054, 0), (0.054, 0.060), (0.046, 0.066)], gr, (dx, yc - 0.020, 0.205), '-Y', segs=48)
    lathe('насос кольцо', [(0.049, 0.064), (0.049, 0.074), (0.040, 0.074), (0.040, 0.064)], mat('pumpblue', rough=0.4), (dx, yc - 0.020, 0.205), '-Y', segs=48)
    box('насос клеммная коробка', (0.050, 0.040, 0.050), mat('bblack', rough=0.5), (dx + 0.040, yc - 0.050, 0.235))
    # термометры сверху: стебель от трубы и циферблат в кармане кожуха
    for sx, col in ((-1, 'bblue'), (1, 'bred')):
        x = sx * dx
        tube('термометр стебель', [(x, yc, H - 0.070), (x, -A + 0.012, H - 0.070)], 0.006, ni)
        lathe('термометр кольцо', [(0.030, 0), (0.030, 0.008), (0.025, 0.008), (0.025, 0.002)], mat(col, rough=0.4), (x, -A + 0.004, H - 0.070), '-Y', segs=44)
        lathe('термометр шкала', [(0.001, 0.005), (0.025, 0.005)], mat('bscreen', rough=0.3), (x, -A + 0.004, H - 0.070), '-Y', segs=44)
    box('логотип', (0.074, 0.0012, 0.022), mat('bscreen', rough=0.4), (0, -A - 0.0004, 0.040))
    # присоединения: низ G1 1/2" НР, верх Rp1" ВР
    out = []
    for sx, nm in ((-1, 'bottom_left'), (1, 'bottom_right')):
        lathe('патрубок низ', [(0.0262, 0), (0.0262, 0.008)] + thread(0.0240, 0.020, start=0.008), yb,
              (sx * dx, yc, 0.006), '-Z', segs=40)
        out.append(port(nm, Vector((sx * dx, yc, -0.022)), (0, 0, -1), 'M', '1 1/2"', 'паспорт SDG-0002 табл. 4.2: G 1 1/2" НР'))
    for sx, nm in ((-1, 'top_left'), (1, 'top_right')):
        hexnut('патрубок верх', 0.044, 0.026, ni, (sx * dx, yc, H - 0.026), 'Z')
        out.append(port(nm, Vector((sx * dx, yc, H)), (0, 0, 1), 'F', '1"', 'паспорт SDG-0002 табл. 4.2: Rp 1" ВР; шаг верхних патрубков паспорт не даёт, принят F=125'))
    return out
