"""
Насосная группа STOUT SDG-0002 (DN25, четырёхходовой термостатический клапан) для tools/export_parts_glb.py.
Не запускается сама: экспортёр выполняет файл в пространстве имён сборщика соседней сессии
(tools/render_hydro_node.py), поэтому кожух, трубы, краны-термометры и насос — ровно те же, что на
её кадрах (группа «под сервопривод» SDG-0003 с тем же перепуском). Меняется одно: вместо сервопривода на штоке
стоит термостатическая головка клапана (паспорт SDG-0002 ред. 3, поз. 5).
"""


def group_mix4(xc=0.0, z0=0.0):
    group(xc, z0, 's')
    for ob in list(bpy.data.objects):
        if ob.name.startswith('сервопривод') or ob.name.startswith('ручка сервопривода'):
            bpy.data.objects.remove(ob, do_unlink=True)
    dx, zb = 0.0625, z0 + 0.032
    part('head')
    # термостатическая головка: серый корпус, рифлёная шкала настройки, красная метка
    lathe('термоголовка', [(0.001, 0), (0.024, 0), (0.024, 0.044), (0.020, 0.050), (0.001, 0.050)], mat('servo', rough=0.45),
          (xc + dx, YA - 0.026, zb + 0.023), '-Y', segs=40, knurl=0.0238)
    lathe('шкала головки', [(0.001, 0.0505), (0.018, 0.0505)], mat('dial', rough=0.4), (xc + dx, YA - 0.026, zb + 0.023), '-Y', segs=40)
    box('метка', (0.004, 0.001, 0.014), mat('bred', rough=0.4), (xc + dx, YA - 0.0770, zb + 0.023 + 0.008))
