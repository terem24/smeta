# -*- coding: utf-8 -*-
"""
Детали нижнего подключения радиатора — общие для кадров Space (render_rad_node.py) и стальных
панельных Ventil (render_panel_node.py). Ось Z — вверх, пол на z = 0, стена — плоскость y = yw,
зритель со стороны −Y.

  svh(xs, ztop, angled)      — узел SVH-0004 (угловой) / SVH-0002 (прямой), паспорт п. 4.2
  nipple_sft0049(x, ztop)    — ниппель SFT-0049 1/2" НР x 3/4" НР (Ventil: нижние патрубки ВР 1/2")
  ek(loc, axis)              — евроконус 16 на выход узла
  wall_run(x, p0, sup, yw)   — угловой узел: труба в стену, поворот вниз в штробе на фиксаторе 90°
  gtube_kit(x, zout, sup)    — прямой узел: компрессионный фитинг 15x3/4" (SFC-0027), Г-образная
                               трубка 16/500 (SFA-0025 / RFA-0025) в пол, колено в стяжке,
                               аксиальный конец с гильзой и труба 16 в стяжке
  floor_bracket(xs)          — фиксирующая скоба для трубок SFA-0000-162025 на полу
  rht_head(c, ax)            — термоголовка ROMMER RHT-0001-103015 (фото)
Состав — ровно то, что кладёт смета (раздел 3.1): угловой — SVH-0004, евроконусы, фиксаторы 90°,
втулки; прямой — SVH-0002, фитинги компрессионные 15x3/4", трубки Г-образные 16/500, скоба.
"""
import math

from blender_parts import *  # noqa: F401,F403
from mathutils import Vector, Matrix

R5D = 0.078                          # поворот трубы 16 на фиксаторе — 5D по оси (паспорт SFA-0029)


def svh(xs, ztop, angled, anch=None):
    """Узел нижнего подключения SVH (паспорт, п. 4.2): накидные гайки SW 30 (ВР 3/4") сверху на
    ниппели прибора, корпуса с винтами запорных клапанов к зрителю, перемычка; выходы G 3/4" НР —
    у прямого вниз (H 46,5 от верха гайки), у углового назад, к стене (H1 36,6 до оси).
    Возвращает [(точка выхода, ось)] в порядке xs."""
    ni = M_NICKEL()
    outs = []
    for x in xs:
        hexnut('гайка узла', 0.030, 0.012, ni, (x, 0, ztop - 0.012), 'Z', ch=0.14)
        if angled:
            lathe('корпус узла', [(0.0, -0.014), (0.0125, -0.014), (0.0135, -0.010), (0.0135, 0.010), (0.0125, 0.014),
                                  (0.0, 0.014)], ni, (x, 0, ztop - 0.0366), 'Z', segs=40)
            lathe('выход узла', [(0.0125, 0), (0.0125, 0.006)] + thread(0.0128, 0.010, start=0.006), ni,
                  (x, 0.0125, ztop - 0.0366), 'Y', segs=40)
            outs.append(((x, 0.0285, ztop - 0.0366), 'Y'))
        else:
            lathe('корпус узла', [(0.0125, 0), (0.0135, 0.004), (0.0135, 0.020), (0.0125, 0.024)], ni,
                  (x, 0, ztop - 0.036), 'Z', segs=40)
            lathe('выход узла', thread(0.0128, 0.0105), ni, (x, 0, ztop - 0.036), '-Z', segs=40)
            outs.append(((x, 0, ztop - 0.0465), '-Z'))
        lathe('винт клапана', [(0.0, 0), (0.0045, 0), (0.0045, 0.004), (0.0, 0.0045)], ni,
              (x, -0.0135, ztop - 0.026), '-Y', segs=20)
    xa, xb = sorted(xs)
    lathe('перемычка', [(0.0055, 0), (0.0055, xb - xa)], ni, (xa, 0, ztop - 0.026), 'X', segs=24)
    marks['node'] = ((xa + xb) / 2, -0.010, ztop - 0.022)
    return outs


def nipple_sft0049(x, ztop):
    """Ниппель SFT-0049-000002 (фото): латунь, НР 1/2" вкручен в нижний патрубок прибора (ВР 1/2"),
    буртик с чёрным уплотнительным кольцом, ниже НР 3/4" под накидную гайку узла. Возвращает низ."""
    br = M_BRASS()
    lathe('буртик ниппеля', [(0.0150, 0), (0.0150, 0.004)], br, (x, 0, ztop), '-Z', segs=40)
    lathe('кольцо ниппеля', [(0.0140, 0), (0.0140, 0.0025)], mat('black', rough=0.6), (x, 0, ztop - 0.004), '-Z', segs=40)
    lathe('ниппель 3/4', thread(0.0128, 0.010), br, (x, 0, ztop - 0.0065), '-Z', segs=40)
    return ztop - 0.0165


def ek(loc, axis):
    """Евроконус 16x2.2 (фото SFC-0020-001622) на выход узла по оси axis ('Y' — к стене, '-Z' — вниз)."""
    if axis == 'Y':
        T = Matrix.Translation(Vector(loc)) @ Matrix.Rotation(math.pi / 2, 4, 'X')   # -Z -> +Y
        transformed(T, ek_fit, (0, 0, 0), '-Z')
        return (loc[0], loc[1] + 0.0218, loc[2])
    ek_fit(loc, axis)
    return (loc[0], loc[1], loc[2] - 0.0218)


def wall_run(x, p0, sup, yw, anch, col_sup='ins_sup', col_ret='ins_ret'):
    """Угловой узел: труба 16 от евроконуса в стену, в штробе поворот вниз на фиксаторе 90°
    (радиус 5D), защитная втулка на выходе трубы из стены."""
    key = 's' if sup else 'r'
    pm = M_PLAST(col_sup if sup else col_ret) if illus() else M_PLAST('pex')
    R = R5D
    y0, z0 = p0[1], p0[2]
    yc = yw - 0.004
    pts = [(x, y0 - 0.004, z0), (x, yc, z0)]
    arc = [(x, yc + R * math.sin(t), z0 - R + R * math.cos(t)) for t in [k * math.pi / 2 / 14 for k in range(1, 15)]]
    part('tube:' + key)
    tube('труба 16', pts + arc + [(x, yc + R, -0.06)], 0.008, pm)
    part('fix:' + key)
    pipe_fixator90((x, yc, z0 - R), (0, 0, 1), (0, 1, 0), R)
    anch['fix:' + key] = (x, yc + R * math.sin(math.pi / 4), z0 - R + R * math.cos(math.pi / 4))
    part('sleeve:' + key)
    lathe('втулка', [(0.0098, 0), (0.0108, 0.002), (0.0108, 0.058), (0.0098, 0.060)],
          mat('sleeve_r' if sup else 'sleeve_b', rough=0.45), (x, yw - 0.030, z0), 'Y', segs=32)


def gtube_kit(x, zout, sup, anch, col_sup='ins_sup', col_ret='ins_ret'):
    """Прямой узел снизу из пола — набор смет: фитинг компрессионный 15x3/4" SFC-0027-001520 (фото:
    крупная никелированная накидная гайка с выступами под ключ) на НР выхода узла; трубка Г-образная
    16/500 SFA-0025/RFA-0025 (фото: тонкая хромированная трубка D 15, длинное плечо вниз, на конце
    короткое колено с аксиальным штуцером) — вниз в пол, колено в стяжке к зрителю; на штуцере —
    монтажная гильза 16 и труба 16 в стяжке. Возвращает ничего; зоны: ek — фитинг, tube — трубка
    и труба."""
    key = 's' if sup else 'r'
    ni = M_NICKEL()
    part('ek:' + key)
    lathe('фитинг компрессионный', [(0.0160, 0), (0.0175, 0.002), (0.0175, 0.018), (0.0150, 0.022), (0.0085, 0.024)],
          ni, (x, 0, zout + 0.010), '-Z', segs=48, ribs=(6, 0.06, 0.003, 0.017))
    part('tube:' + key)
    ch = M_CHROME()
    zt = zout - 0.012
    zf = -0.045                                   # колено в стяжке
    R = 0.022
    arc = [(x, -R + R * math.cos(t), zf + R - R * math.sin(t)) for t in [k * math.pi / 2 / 10 for k in range(11)]]
    tube('трубка Г-образная', [(x, 0, zt)] + [(x, 0, zf + R)] + arc[1:] + [(x, -R - 0.030, zf)], 0.0075, ch)
    yb = -R - 0.030
    br = M_BRASS()
    lathe('штуцер аксиальный', [(0.0080, 0), (0.0095, 0.004), (0.0080, 0.010), (0.0095, 0.014), (0.0080, 0.020)], br,
          (x, yb, zf), '-Y', segs=32)
    lathe('гильза', [(0.0115, 0), (0.0115, 0.020), (0.0105, 0.022)], br, (x, yb - 0.004, zf), '-Y', segs=40)
    pm = M_PLAST(col_sup if sup else col_ret) if illus() else M_PLAST('pex')
    tube('труба 16', [(x, yb - 0.010, zf), (x, yb - 0.110, zf)], 0.008, pm)
    anch['tube:' + key] = (x, 0, (zt + 0.0) / 2)


def floor_bracket(xs, anch):
    """Фиксирующая скоба для трубок SFA-0000-162025 (фото): оцинкованная пластина на полу, на ней
    гнутая стойка с двумя полукруглыми гнёздами под трубки (межосевое — по узлу)."""
    part('fix:b')
    zn = metal('zinc')
    xa, xb = sorted(xs)
    xc = (xa + xb) / 2
    box('пластина скобы', (xb - xa + 0.050, 0.045, 0.0018), zn, (xc, -0.002, 0.0009))
    box('стойка скобы', (xb - xa + 0.036, 0.0018, 0.030), zn, (xc, 0.012, 0.016))
    for x in xs:
        lathe('гнездо', [(0.0090, 0), (0.0090, 0.012)], zn, (x, 0.004, 0.026), 'Y', segs=20)
    lathe('винт скобы', [(0.0035, 0), (0.0035, 0.004), (0.0, 0.0045)], M_NICKEL(), (xc, -0.012, 0.0018), 'Z', segs=16)
    anch['fix:b'] = (xc, -0.010, 0.010)


def rht_head(c, ax):
    """Термоголовка ROMMER RHT-0001-103015 (фото): никелированная гайка с накаткой, чёрное кольцо,
    белый корпус со шкалой 1–5 и указателем, ребристый колпак с плоским торцом."""
    ni = M_NICKEL()
    d = {'X': Vector((1, 0, 0)), '-X': Vector((-1, 0, 0)), 'Z': Vector((0, 0, 1))}[ax]
    c = Vector(c)
    part('head')
    lathe('гайка головки', [(0.0160, 0), (0.0165, 0.001), (0.0165, 0.012), (0.0155, 0.013)], ni, tuple(c), ax,
          segs=48, knurl=0.0163)
    lathe('кольцо чёрное', [(0.0200, 0), (0.0205, 0.002), (0.0205, 0.006)], mat('black', rough=0.5), tuple(c + d * 0.013), ax, segs=48)
    w = mat('headwhite', rough=0.40, coat=0.3)
    lathe('термоголовка RHT', [(0.0240, 0), (0.0255, 0.004), (0.0255, 0.026), (0.0245, 0.030), (0.0235, 0.034), (0.0225, 0.064),
                               (0.0200, 0.070), (0.0, 0.072)], w, tuple(c + d * 0.019), ax, segs=80, sharp=40,
          ribs=(16, 0.08, 0.034, 0.066))
    side = Vector((0, -1, 0)) if ax != 'Z' else Vector((0, -1, 0))
    up = d.cross(side).normalized()
    dark = mat('scaleink', rough=0.5)
    for k in range(-3, 4):
        a = math.radians(k * 15)
        p = c + d * (0.031 if k % 2 else 0.033) + (side * math.cos(a) + up * math.sin(a)) * 0.0257
        size = (0.006 if not k % 2 else 0.003, 0.0008, 0.0012) if ax != 'Z' else (0.0012, 0.0008, 0.006 if not k % 2 else 0.003)
        box('цифра шкалы', size, dark, tuple(p))
    marks['head'] = tuple(c + d * 0.050 + side * 0.025)
