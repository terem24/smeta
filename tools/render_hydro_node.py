def collector16(n):
    """SDG-0016-00400<n> (DN25, n пар выходов) с кронштейнами и SDG-0015-004001 под ним. Возвращает x верхних патрубков
    и верх гаек (как collector). Слева и справа на торцах стрелки — заглушки 1/2" НР,
    спереди — термометр, к котлу снизу — муфты 1 1/2" x 1"."""
    L = 0.250 * n + 0.040
    B = 0.250 * n - 0.125
    H, D = 0.172, 0.140
    l = 0.125
    part('mf')
    epp = mat('epp', rough=0.9)
    st = mat('steelblk', rough=0.45, metal=0.5)
    sec = rounded([(-L / 2, -D / 2), (L / 2, -D / 2), (L / 2, D / 2), (-L / 2, D / 2)], 0.028, seg=5)
    prism('кожух коллектора', [(u, v + YA) for u, v in sec], H, epp, Matrix.Translation(Vector((0, 0, ZC))), bevel=0.006)
    photo_quad('наклейка STOUT', _tex('stout_label'), (0, 0, 960, 400), (-L / 2 + 0.058, YA - D / 2 - 0.0006, ZC - 0.050), TO_XZ, 0.064, 0.0267, size=(960, 400))
    marks['mf'] = (-L / 2 + 0.150, YA - D / 2, ZC + 0.015)
    xs = []
    for k in range(n):
        xc = (k - (n - 1) / 2) * 0.250
        xs += [xc - l / 2, xc + l / 2]
    zt, zb = ZC + H / 2, ZC - H / 2
    for x in xs:
        lathe('патрубок верх', [(0.022, 0), (0.022, 0.018)], st, (x, YA, zt), 'Z', segs=40)
        hexnut('накидная гайка G1 1/2', 0.058, 0.020, mat('steelblk', rough=0.5, metal=0.4), (x, YA, zt + 0.016), 'Z')
    # кронштейны к стене: колено вниз и к стене, планка с отверстием (паспорт, чертёж: поз. B, E)
    zbk = zb - 0.050
    for sx in (-1, 1):
        tube('кронштейн', [(sx * B / 2, YA, zb + 0.020), (sx * B / 2, YA, zbk), (sx * B / 2, YW + 0.006, zbk)], 0.0105, st)
        box('планка кронштейна', (0.040, 0.004, 0.070), st, (sx * B / 2, YW + 0.004, zbk))
    # снизу по центру: два НР G1 1/2" в ВР порты стрелки
    for sx in (-1, 1):
        lathe('патрубок вниз НР', [(0.022, 0), (0.022, 0.012)] + thread(0.0240, 0.020, start=0.012), st, (sx * l / 2, YA, zb), '-Z', segs=40)
    # стрелка SDG-0015-004001: порты ВР сверху, корпус ЕРР 257 x 125 x 125, порты НР снизу
    part('sep')
    zta = zb - 0.034                                          # верх корпуса стрелки
    zs = zta - SEP_H / 2                                      # ось стрелки
    ya = YA
    sec2 = rounded([(-SEP_L / 2, -SEP_H / 2), (SEP_L / 2, -SEP_H / 2), (SEP_L / 2, SEP_H / 2), (-SEP_L / 2, SEP_H / 2)], 0.034, seg=5)
    prism('гидрострелка SDG-0015', [(u, v + ya) for u, v in sec2], SEP_H, epp, Matrix.Translation(Vector((0, 0, zs))), bevel=0.006)
    photo_quad('наклейка STOUT на стрелке', _tex('stout_label'), (0, 0, 960, 400), (-SEP_L / 2 + 0.055, ya - SEP_H / 2 - 0.0006, zs - 0.030), TO_XZ, 0.054, 0.0225, size=(960, 400))
    marks['sep'] = (-SEP_L / 2 + 0.040, ya - SEP_H / 2, zs + 0.015)
    pb = mat('black', rough=0.55)
    for sx in (-1, 1):
        hexnut('порт ВР сверху', 0.056, 0.034, pb, (sx * l / 2, ya, zta - 0.002), 'Z', ch=0.14)
        lathe('порт НР снизу', [(0.0310, 0), (0.0310, 0.012), (0.0240, 0.012), (0.0240, 0.022)] + thread(0.0240, 0.016, start=0.022), pb,
              (sx * l / 2, ya, zs - SEP_H / 2 + 0.002), '-Z', segs=40)
    zbs = zs - SEP_H / 2 - 0.036                              # низ резьбы портов
    # муфты ВР 1 1/2" x ВР 1" (SFT-0005) к котлу
    part('tube')
    br = M_BRASS()
    for sx in (-1, 1):
        lathe('муфта 1 1/2 x 1', [(0.0, 0), (0.0285, 0), (0.0300, 0.004), (0.0300, 0.024), (0.0250, 0.030), (0.0230, 0.032),
                                  (0.0230, 0.046), (0.0215, 0.048), (0.0, 0.048)], br, (sx * l / 2, ya, zbs + 0.020), '-Z', segs=48)
        lathe('устье 1', [(0.0, 0), (0.0170, 0), (0.0170, 0.002)], mat('black', rough=0.6), (sx * l / 2, ya, zbs + 0.020 - 0.0485), '-Z', segs=32)
    ANCH['tube:a'] = (-l / 2, ya, zbs - 0.026)
    marks['tube'] = (-l / 2, ya - 0.030, zbs - 0.026)
    # слева на торце: штуцер G1/2 под заглушку (кран слива в смете не нужен), заглушка НР 1/2" SFT-0024
    part('feed')
    xl, zk = -SEP_L / 2, zs - 0.020
    plug_brass(xl, ya, zk, -1)
    # справа на торце: такой же штуцер G1/2 под заглушку (воздух снимают воздухоотводчики узлов МУ-25М над группами)
    part('feed')
    xr, zv = SEP_L / 2, zs + 0.020
    plug_brass(xr, ya, zv, 1)
    # спереди: штуцер термометра, чуть правее середины (чертёж SDG-0015)
    part('th')
    lathe('штуцер G1/2 спереди', [(0.0125, 0), (0.0125, 0.008)], br, (0.040, ya - SEP_H / 2 + 0.002, zs), '-Y', segs=24)
    thermometer(0.040, ya - SEP_H / 2 - 0.006, zs)
    return xs, zt + 0.036


