def collector(n):
    """Кожух ЕРР, сверху патрубки с накидными гайками G1 1/2", снизу НР G1 1/2" к котлу с муфтами 1 1/2" × 1",
    на торцах G 1/2" ВР: слева сливной кран, справа заглушка. Возвращает x верхних патрубков и верх гаек."""
    L = {2: 0.525, 3: 0.790}[n]
    A = {2: 0.320, 3: 0.270}[n]
    B = {2: 0.200, 3: 0.450}[n]
    l = 0.125
    part('mf')
    epp = mat('epp', rough=0.9)
    sec = rounded([(-L / 2, -CH / 2), (L / 2, -CH / 2), (L / 2, CH / 2), (-L / 2, CH / 2)], 0.025, seg=5)
    prism('кожух коллектора', [(u, v + YA) for u, v in sec], CH, epp, Matrix.Translation(Vector((0, 0, ZC))), bevel=0.006)
    box('логотип', (0.048, 0.001, 0.014), mat('bwhite', rough=0.4), (-L / 2 + 0.055, YA - CH / 2 - 0.0005, ZC - 0.040))
    marks['mf'] = (-L / 2 + 0.150, YA - CH / 2, ZC + 0.010)
    xs = []
    for k in range(n):
        xc = (k - (n - 1) / 2) * A
        xs += [xc - l / 2, xc + l / 2]
    st = mat('steelblk', rough=0.45, metal=0.5)
    for x in xs:
        lathe('патрубок верх', [(0.022, 0), (0.022, 0.018)], st, (x, YA, ZC + CH / 2), 'Z', segs=40)
        hexnut('накидная гайка G1 1/2', 0.058, 0.020, M_NICKEL(), (x, YA, ZC + CH / 2 + 0.016), 'Z')
    # к котлу: патрубки НР G1 1/2" и муфты ВР 1 1/2" × ВР 1" (SFT-0005)
    br = M_BRASS()
    for sx in (-1, 1):
        lathe('патрубок к котлу', [(0.022, 0), (0.022, 0.016)] + thread(0.0240, 0.018, start=0.016), st,
              (sx * B / 2, YA, ZC - CH / 2), '-Z', segs=40)
    part('tube')
    for sx in (-1, 1):
        z = ZC - CH / 2 - 0.022
        lathe('муфта 1 1/2 x 1', [(0.0, 0), (0.0285, 0), (0.0300, 0.004), (0.0300, 0.024), (0.0250, 0.030), (0.0230, 0.032),
                                  (0.0230, 0.046), (0.0215, 0.048), (0.0, 0.048)], br, (sx * B / 2, YA, z), '-Z', segs=48)
        lathe('устье 1', [(0.0, 0), (0.0170, 0), (0.0170, 0.002)], mat('black', rough=0.6), (sx * B / 2, YA, z - 0.0485), '-Z', segs=32)
    ANCH['tube:a'] = (-B / 2, YA, ZC - CH / 2 - 0.045)
    marks['tube'] = (-B / 2, YA - 0.030, ZC - CH / 2 - 0.045)
    # торцы: G 1/2" ВР (паспорт, п. 5 — для вертикальной установки); слева слив, справа заглушка
    zp = ZC - 0.035
    part('ek')
    xl = -L / 2
    lathe('кран слива корпус', [(0.0, 0), (0.0085, 0), (0.0085, 0.010), (0.0135, 0.014), (0.0145, 0.022), (0.0145, 0.030),
                                  (0.0135, 0.036), (0.0085, 0.040), (0.0085, 0.052), (0.0, 0.052)], M_NICKEL(), (xl, YA, zp), '-X', segs=40)
    lathe('кран слива НР', thread(0.0104, 0.010), M_BRASS(), (xl - 0.052, YA, zp), '-X', segs=32)
    transformed(Matrix.Translation(Vector((xl - 0.026, YA, zp))) @ Matrix.Rotation(math.pi, 4, 'Z') @ UP_STEM, butterfly, 0, 0, 'black')
    marks['ek'] = (xl - 0.026, YA - 0.010, zp + 0.030)
    part('feed')
    hexnut('заглушка торца', 0.024, 0.010, br, (L / 2, YA, zp), 'X')
    return xs, ZC + CH / 2 + 0.036


def askon(c, vent):
    """Узел ASKON МУ-25М на верхний кран группы (Rp 1"): длинный никелированный патрубок НР 1" вниз в кран,
    корпус поперёк — 1" ВР вперёд к трубе системы, 1/2" ВР к стене, 1/2" ВР вверх. vent — на верхний отвод
    отсечной клапан SVC-1003 и воздухоотводчик SVS-1011, иначе заглушка; на отводе к стене — заглушка."""
    ni = M_NICKEL()
    br = M_BRASS()
    c = Vector(c)
    part('feed')
    lathe('патрубок НР 1', thread(0.0166, 0.014), ni, tuple(c + Vector((0, 0, -0.012))), 'Z', segs=40)
    lathe('патрубок', [(0.0170, 0), (0.0170, 0.085)], ni, tuple(c + Vector((0, 0, 0.002))), 'Z', segs=40)
    zb = c.z + 0.105                                      # ось корпуса
    lathe('корпус МУ', [(0.0, 0), (0.0215, 0), (0.0215, 0.070), (0.0, 0.070)], ni, (c.x, c.y + 0.030, zb), '-Y', segs=48)
    lathe('устье 1 ВР', [(0.0240, 0), (0.0240, 0.012), (0.0175, 0.012), (0.0175, 0.004)], ni, (c.x, c.y - 0.040, zb), '-Y', segs=48)
    lathe('отвод к стене', [(0.0150, 0), (0.0150, 0.012)], ni, (c.x, c.y + 0.030, zb), 'Y', segs=36)
    lathe('отвод вверх', [(0.0150, 0), (0.0150, 0.018)], ni, (c.x, c.y, zb + 0.018), 'Z', segs=36)
    hexnut('заглушка к стене', 0.024, 0.008, br, (c.x, c.y + 0.042, zb), 'Y')
    marks['feed'] = (c.x - 0.022, c.y - 0.020, zb)
    zt = zb + 0.036
    if vent:
        part('mount')
        hexnut('отсечной клапан', 0.024, 0.016, ni, (c.x, c.y, zt), 'Z')
        lathe('воздухоотводчик', [(0.0, 0), (0.0090, 0), (0.0090, 0.004), (0.0170, 0.008), (0.0170, 0.048), (0.0140, 0.052), (0.0, 0.054)],
              ni, (c.x, c.y, zt + 0.016), 'Z', segs=48)
        lathe('колпачок', [(0.0, 0), (0.0055, 0), (0.0055, 0.010), (0.0, 0.011)], mat('capblue', rough=0.4), (c.x, c.y, zt + 0.070), 'Z', segs=24)
        marks['mount'] = (c.x, c.y - 0.017, zt + 0.045)
    else:
        part('feed')
        hexnut('заглушка вверх', 0.024, 0.008, br, (c.x, c.y, zt), 'Z')


def thermo_valve(c, col):
    """Верхний кран группы по фото SDG-0001/0003 (масштаб по ширине группы 247 мм): снизу крупная латунная
    гайка 55 x 20 (на насос или на вставку), шейка, литой корпус-шар с двумя боковыми шестигранниками штуцеров
    (байпас/заглушки), спереди ручка-термометр Ø62 — рифлёное кольцо (синее у обратки, красное у подачи), хромовый
    ободок, белая шкала 0…120 со стрелкой; сверху гнездо Rp 1" (до верха 363 от низа группы). Возвращает верх гнезда."""
    br = M_BRASS()
    c = Vector(c)
    hexnut('гайка крана низ', 0.055, 0.020, br, tuple(c), 'Z', ch=0.10)
    lathe('шейка крана', [(0.0175, 0), (0.0175, 0.008), (0.0215, 0.010)], br, tuple(c + Vector((0, 0, 0.020))), 'Z', segs=48)
    zc = c.z + 0.052                                      # центр шара и термометра
    lathe('корпус крана', [(0.0215, 0), (0.0255, 0.006), (0.0270, 0.020), (0.0270, 0.034), (0.0250, 0.044), (0.0205, 0.050)],
          br, (c.x, c.y, c.z + 0.028), 'Z', segs=56, sharp=40)
    for sx in (-1, 1):
        lathe('боковая бобышка', [(0.0110, 0), (0.0110, 0.012)], br, (c.x + sx * 0.024, c.y, zc + 0.012), 'X' if sx > 0 else '-X', segs=24)
        hexnut('боковой шестигранник', 0.024, 0.012, br, (c.x + sx * 0.036, c.y, zc + 0.012), 'X' if sx > 0 else '-X')
    # гнездо Rp 1": латунный стакан с тёмным устьем
    lathe('гнездо Rp1', [(0.0215, 0), (0.0215, 0.024), (0.0170, 0.024), (0.0170, 0.012)], br, (c.x, c.y, c.z + 0.078), 'Z', segs=48)
    # ручка-термометр
    yf = c.y - 0.026
    lathe('кольцо термометра', [(0.0, 0), (0.031, 0), (0.031, 0.013), (0.028, 0.016), (0.0, 0.016)], mat(col, rough=0.35),
          (c.x, yf, zc), '-Y', segs=72, ribs=(24, 0.05, 0.001, 0.012))
    # ободок — открытое кольцо: с закрытыми торцами его диск ложился поверх шкалы, и термометр выходил пустым
    lathe('ободок', [(0.0228, 0.0158), (0.0255, 0.0158), (0.0255, 0.0185), (0.0230, 0.0190), (0.0228, 0.0186)], M_CHROME(),
          (c.x, yf, zc), '-Y', segs=64, caps=False)
    lathe('шкала', [(0.0, 0.0172), (0.0232, 0.0172)], mat('dial', rough=0.3), (c.x, yf, zc), '-Y', segs=64)
    if SEP16:
        # кадры «…_s»: циферблат — текстура (деления, цифры 0…120, °C, STOUT, стрелка)
        photo_disc('циферблат', _tex('thermo_dial'), (512, 512, 512, 512), (c.x, yf - 0.0174, zc), '-Y', 0.0232, size=(1024, 1024))
        return c + Vector((0, 0, 0.102))
    # печатная шкала: дуга делений 0…120 °C и цифры (на фото — чёрные по белому, дуга на 270°)
    for k in range(25):
        a = math.radians(-135 + 11.25 * k)
        big = k % 4 == 0
        box('деление', (0.0010, 0.0006, 0.0045 if big else 0.0025), mat('logo', rough=0.4),
            (c.x + 0.0195 * math.sin(a), yf - 0.0176, zc + 0.0195 * math.cos(a)))
        if big:
            box('цифра', (0.0030, 0.0006, 0.0022), mat('logo', rough=0.4),
                (c.x + 0.0140 * math.sin(a), yf - 0.0176, zc + 0.0140 * math.cos(a)))
    box('стрелка', (0.017, 0.0008, 0.0014), mat('logo', rough=0.4), (c.x - 0.006, yf - 0.0180, zc + 0.002))
    lathe('ось стрелки', [(0.0, 0.0175), (0.0022, 0.0175), (0.0022, 0.0186), (0.0, 0.0188)], mat('logo', rough=0.4), (c.x, yf, zc), '-Y', segs=16)
    return c + Vector((0, 0, 0.102))


