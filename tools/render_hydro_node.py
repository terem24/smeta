def _bb(o):
    ws = [o.matrix_world @ Vector(c) for c in o.bound_box]
    return [min(w[i] for w in ws) for i in range(3)], [max(w[i] for w in ws) for i in range(3)]


def check_joints(tol=0.003):
    objs = [(o.name, _bb(o)) for o in coll('solid').objects if o.type in ('MESH', 'CURVE')]
    bad = 0
    for a, b in JOINTS:
        bs = b if isinstance(b, tuple) else (b,)
        la = [x for x in objs if x[0].split('.')[0] == a]
        lb = [x for x in objs if x[0].split('.')[0] in bs]
        if not la or not lb:
            continue
        for na, (a0, a1) in la:
            ok = False
            for nb, (b0, b1) in lb:
                if all(a0[i] <= b1[i] + tol and b0[i] <= a1[i] + tol for i in range(3)):
                    ok = True
                    break
            if not ok:
                bad += 1
                print('СТЫК: «%s» не касается «%s» (%s)' % (a, b, na))
    print('СТЫКИ: проверено %d пар, разрывов %d' % (len(JOINTS), bad))


