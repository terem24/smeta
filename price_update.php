     * всему прайсу: 380 попаданий, ни одного в листах других брендов.
     */
    $reCanon = '/\b([SR][A-Z]{1,4}\d?-\d{3,4}[A-Z]{0,2}-\d{4,8}[A-Z]?)\b/u';

    /**
     * Тот же артикул, но написанный ЧЕРЕЗ ПРОБЕЛЫ: «SMS 0907 000002».
     *
     * Так заполнен весь лист «STOUT Коллекторы» и часть «STOUT Шаровые краны».
     * Проверка колонки ниже отбрасывает значения с пробелами как «не код» — и
     * колонка, честно подписанная в шапке «Артикул», оказывалась по её меркам
     * пустой, после чего подменялась колонкой нумерации. Отсюда в индексе
     * брались артикул «1» и наименование «8207».
     */
    $reCanonSp = '/\b([SR][A-Z]{1,4}\d?[ -]\d{3,4}[A-Z]{0,2}[ -]\d{4,8}[A-Z]?)\b/u';
    /** Приводим к каноническому виду: пробелы между частями — те же дефисы. */
    $canonize = static function ($v) use ($reCanon, $reCanonSp) {
        $v = trim((string)$v);
        if ($v === '' || preg_match($reCanon, $v)) return $v;
        if (preg_match($reCanonSp, $v, $m)) {
            return str_replace($v, preg_replace('/\s+/u', '-', $m[1]), $v);
        }
        return $v;
    };

    /**
     * Схлопывание пробелов, устойчивое к битой кодировке.
     *
     * preg_replace с модификатором /u возвращает NULL, если в строке не
     * UTF-8, — а такие ячейки в прайсе попадаются. Название становилось null,
     * и позиция уходила в индекс безымянной. Не вышло по-юникодному —
     * схлопываем побайтово: это хуже, но лучше, чем потерять строку.
     */
    $squash = static function ($v) {
        $v = (string)$v;
        $r = preg_replace('/\s+/u', ' ', $v);
        return trim($r === null ? preg_replace('/\s+/', ' ', $v) : $r);
    };

    /**
     * Короткая «шапка» названия блока — то, что наследуют строки-продолжения.
     *
     * Наименование серии написано один раз, в первой строке блока, и написано
     * подробно: «Коллектор с расходомерами: - 1 обратный коллектор с отсечными
     * клапанами под электротермоприводы - 1 подающий коллектор…». Подставлять
     * это целиком в каждую строку нельзя: описание у всей серии одинаковое, а
     * длина названия в индексе ограничена — размер, единственное, чем строки
     * блока и различаются, вытеснялся бы за предел.
     *
     * Берём часть до двоеточия: там стоит сам предмет.
     */
    $blockHead = static function ($v) use ($squash) {
        $v = $squash($v);
        $p = mb_strpos($v, ':');
        if ($p !== false && $p >= 3) $v = mb_substr($v, 0, $p);
        if (mb_strlen($v) > 60) {
            $cut = mb_substr($v, 0, 60);
            $sp = mb_strrpos($cut, ' ');
            $v = ($sp !== false && $sp >= 20) ? mb_substr($cut, 0, $sp) : $cut;
        }
        return trim($v, " ,;-–—");
    };

    /** Строка-шапка: по ней таблица и опознаётся. */
    $isHeader = static function ($r) use ($reArt, $reName, $rePrice, $isDiscount) {
        $hasArt = $hasName = $hasPrice = false;
        foreach ($r as $v) {
            $t = trim((string)$v);
            if (preg_match($reArt, $t)) $hasArt = true;
            if (preg_match($reName, $t)) $hasName = true;
            if (preg_match($rePrice, $t) && !$isDiscount($t)) $hasPrice = true;
        }
        return $hasArt || ($hasName && $hasPrice);
    };

    /**
     * Карта колонок для шапки, стоящей в строке $hi.
     *
     * Вынесена в отдельную функцию, потому что на одном листе шапок бывает
     * несколько — см. разбор строк ниже.
     */
    $mapCols = static function ($rows, $hi) use ($reArt, $reName, $rePrice, $reCanon, $reCanonSp, $isDiscount) {
        $hdr = $rows[$hi];
        $cArt = $cPrice = $cName = $cSize = $cEur = null;
        foreach ($hdr as $col => $v) {
            $t = trim((string)$v);
            if ($cArt === null && preg_match($reArt, $t)) $cArt = $col;
            if ($cName === null && preg_match($reName, $t)) $cName = $col;
            if ($cSize === null && preg_match('/размер|типоразмер/ui', $t)) $cSize = $col;
            if (preg_match($rePrice, $t) && !$isDiscount($t)) {
                if (preg_match('/eur|евро/ui', $t)) $cEur = $col;
                // «Цена с НДС, РУБ» приоритетнее, чем в евро.
                if ($cPrice === null || preg_match('/руб/ui', $t)) $cPrice = $col;
            }
        }
        /**
         * Шапка в два яруса.
         *
         * «Rommer Радиаторы стальные трубч» подписан так: в верхней строке
         * «ТИП | Габариты, мм | Тепловая мощность | Цена с НДС, руб.», в нижней
         * «Артикул | Модель | Межцентр. размер | … | Боковое подключение».
         * Шапкой опознаётся нижняя строка — в ней есть «Артикул», — а колонка
         * цены подписана только в верхней. Лист выпадал целиком.
         *
         * Поэтому, не найдя цену в самой шапке, смотрим на две строки выше.
         * Больше не нужно: ярусов глубже двух в прайсе нет.
         */
        for ($up = 1; $up <= 2 && $cPrice === null && $hi - $up >= 0; $up++) {
            foreach ($rows[$hi - $up] as $col => $v) {
                $t = trim((string)$v);
                if (!preg_match($rePrice, $t) || $isDiscount($t)) continue;
                if ($cPrice === null || preg_match('/руб/ui', $t)) $cPrice = $col;
            }
        }

        // Без цены таблица бесполезна. Без артикула — нет: ищем и по названию.
        if (!$cPrice) return null;

        /**
         * Проверка колонки артикула ПО ДАННЫМ.
         *
         * В половине листов первая колонка — «Изображение»/«Внешний вид», и шапка
         * подписана со сдвигом: «Артикул» стоит над колонкой B, а сами коды лежат
         * в A. Генератор читал пустую B, отбрасывал каждую строку и молча терял
         * весь лист — так пропали «STOUT Крепежная система», «Walraven»,
         * «Управляющая автоматика» и ещё 54 листа. Поэтому колонку, названную в
         * шапке, сверяем с товарными строками и при необходимости ищем настоящую.
         */
        /**
         * Колонки, подписанные ценой, в кандидаты на артикул не берём вовсе.
         *
         * Рядом с ценой почти всегда стоит вторая — «с учётом скидки», и
         * значения в ней короткие, без пробелов и все разные, то есть по
         * признакам это идеальный «артикул». Так лист FAR и терял свой код:
         * артикулы там записаны через пробелы («FT 1640 12»), под правило
         * «короткий, без пробелов» они не подходили, и колонка со скидочной
         * ценой уводила выбор на себя. В индексе у 90 позиций листа вместо
         * кода стояла цена, и найти такую позицию было нечем.
         */
        $priceCols = [];
        foreach ($hdr as $col => $v) {
            if (preg_match($rePrice, trim((string)$v))) $priceCols[$col] = 1;
        }

        $probe = [];
        $canon = [];
        // Сколько РАЗНЫХ значений встретилось в колонке — см. $varied ниже.
        $distinct = [];
        // Заполненность колонки БЕЗ отбора по форме: шапку, назвавшую артикул,
        // нельзя отвергать только потому, что коды в ней записаны непривычно.
        $filled = [];
        // Числовых значений в колонке: сплошь числа — это цена или количество.
        $nums = [];
        $seenRows = 0;
        for ($i = $hi + 1; $i < count($rows) && $seenRows < 40; $i++) {
            if (!is_numeric($rows[$i][$cPrice] ?? null)) continue;
            $seenRows++;
            foreach ($rows[$i] as $col => $v) {
                $t = trim((string)$v);
                if ($t === '' || $col === $cPrice || $col === $cName) continue;
                $filled[$col] = ($filled[$col] ?? 0) + 1;
                if (isset($priceCols[$col])) continue;
                // Код товара: короткий, без пробелов, не цена и не название.
                // Исключение — артикул, записанный через пробелы: он код и есть.
                $spacedArt = preg_match($reCanonSp, $t) && !preg_match($reCanon, $t);
                if (!$spacedArt && (mb_strlen($t) > 30 || preg_match('/\s/u', $t))) continue;
                $probe[$col] = ($probe[$col] ?? 0) + 1;
                $distinct[$col][$t] = 1;
                if (is_numeric(str_replace(',', '.', $t))) $nums[$col] = ($nums[$col] ?? 0) + 1;
                if ($spacedArt || preg_match($reCanon, $t)) $canon[$col] = ($canon[$col] ?? 0) + 1;
            }
        }
        /**
         * Колонка артикула по строкам почти не повторяется.
         *
         * Признак «короткое значение без пробелов» одинаково подходит и колонке
         * страны производства: «Россия», «Италия» — короткие, без пробелов и
         * заполнены плотнее артикулов. Так в индекс и попал артикул «Россия» у
         * комплекта настенных кронштейнов для радиаторов, а «Италия» — ещё у
         * четырнадцати позиций; такой код печатается клиенту в смете и по нему
         * не находится фото товара. Отличить их можно, не заводя списка стран:
         * артикулы по строкам РАЗНЫЕ — на сорока строках их сорок, — а стран
         * две-три на весь лист.
         *
         * На трёх строках о повторах судить нельзя, поэтому короткие блоки
         * пропускаем без проверки.
         */
        $varied = static function ($col) use ($probe, $distinct) {
            $n = $probe[$col] ?? 0;
            if ($n < 4) return true;
            return count($distinct[$col] ?? []) * 2 > $n;
        };

        /**
         * Сплошь числа — это не артикул.
         *
         * У листа «Pro Aqua» рядом с кодом стоит колонка размера («110 x 50 м»),
         * а на дренажных позициях — голое число. Разные, короткие, плотные:
         * по признакам артикул, по смыслу нет. Настоящие коды почти всегда
         * несут хоть одну букву, поэтому колонку из одних чисел берём только
         * тогда, когда другой не нашлось вовсе.
         */
        $allNumeric = static function ($col) use ($probe, $nums) {
            $n = $probe[$col] ?? 0;
            return $n > 0 && ($nums[$col] ?? 0) === $n;
        };

        $artFilled = $cArt ? ($filled[$cArt] ?? 0) : 0;
        if ($seenRows > 0 && $artFilled * 2 < $seenRows) {
            arsort($probe);
            // Берём самую плотную из тех, что похожи на артикул. Раньше бралась
            // просто самая плотная, и колонка страны обходила колонку кода.
            foreach ($probe as $col => $n) {
                if ($n * 2 >= $seenRows && $varied($col) && !$allNumeric($col)) { $cArt = $col; break; }
            }
            // Буквенной колонки не нашлось — берём числовую, лишь бы не пустоту.
            if ($cArt === null || ($filled[$cArt] ?? 0) * 2 < $seenRows) {
                foreach ($probe as $col => $n) {
                    if ($n * 2 >= $seenRows && $varied($col)) { $cArt = $col; break; }
                }
            }
        }

        /**
         * Колонка с настоящими артикулами перебивает и шапку, и частотную догадку.
         *
         * Признак «короткое значение без пробелов» слеп к смыслу: в листе «STOUT
         * Конвекторы внутрипольные» ему одинаково нравится и колонка артикулов, и
         * колонка нумерации строк (6810, 6811, 6812…), а выигрывает та, что
         * заполнена плотнее. В индекс уходил номер строки, и по нему потом не
         * находилось ни фото, ни сама позиция, а в смету клиенту печатался
         * «артикул 6810». Там, где артикул канонической формы в листе есть,
         * сомнений быть не может — берём эту колонку.
         */
        /**
         * …но колонку, ЯВНО названную «Артикул», перебиваем только если она
         * артикулов почти не содержит.
         *
         * В листе «Rommer Трубы и фитинги из нерж» колонок с кодами две:
         * «Артикул» (RSS-0002-000015) и «Артикул 2» (RSS-1002-000015). Обе
         * канонические, и по плотности заполнения выигрывала вторая — в индекс
         * уходил код, которого нет ни в каталоге, ни в счетах. Названная в
         * шапке колонка — это утверждение автора прайса, и опровергать его
         * стоит только явным перевесом.
         */
        if ($seenRows > 0 && $canon) {
            arsort($canon);
            $canonCol = key($canon);
            $curCanon = ($cArt !== null) ? ($canon[$cArt] ?? 0) : 0;
            if ($canon[$canonCol] * 2 >= $seenRows && $curCanon * 2 < $canon[$canonCol]) {
                $cArt = $canonCol;
            }
        }

        /**
         * Вторая колонка артикулов — запасная, для строк с пустой первой.
         *
         * В том же листе нержавейки ROMMER «Артикул 1» (RSS-0001-…) заполнен
         * только у ходовых позиций, а у штанг 2 м, российских штанг 4 м и
         * больших диаметров стоит один «Артикул 2» (RSS-1001-200022). Такие
         * строки уходили в индекс вовсе без кода, и найти их по артикулу было
         * нельзя (22.09.2026). Первую колонку не трогаем — берём вторую только
         * там, где в первой пусто.
         */
        $cArt2 = null;
        if ($seenRows > 0 && $canon) {
            foreach ($canon as $col => $n) {
                if ($col !== $cArt && $n * 2 >= $seenRows) { $cArt2 = $col; break; }
            }
        }

        // Рублёвой колонки в этой таблице нет вовсе — цену пересчитаем
        // по курсу самой книги (см. ниже).
        $eurOnly = ($cEur !== null && $cPrice === $cEur);

        /**
         * Слово EURO в шапке — не всегда евро под ней.
         *
         * На листе «De Dietrich» колонка подписана «Цена с НДС, EURO», а стоят
         * в ней рубли: 292 641,57 за настенный котёл на 15 кВт. Умножение на
         * курс превращало его в 32 миллиона, и такими в сентябрьском индексе
         * оказались все 16 позиций листа. Отличить одно от другого можно по
         * порядку величины: настоящие евро-листы прайса — Kiturami, Bugatti,
         * Global, Honeywell, MEIBES, VARMANN, конвекторы STOUT — держатся в
         * пределах пятисот евро за позицию, у самого дорогого из них медиана
         * 477. Полтораста тысяч «евро» за котёл — это рубли с устаревшей
         * подписью.
         */
        if ($eurOnly) {
            $vals = [];
            $cnt = count($rows);
            for ($k = $hi + 1; $k < $cnt && count($vals) < 400; $k++) {
                $v = $rows[$k][$cPrice] ?? null;
                if (is_numeric($v) && (float)$v > 0) $vals[] = (float)$v;
            }
            if ($vals) {
                sort($vals);
                if ($vals[intdiv(count($vals), 2)] > 5000) $eurOnly = false;
            }
        }

        return [
            'art' => $cArt, 'art2' => $cArt2, 'name' => $cName, 'size' => $cSize,
            'price' => $cPrice, 'eur' => $cEur,
            'eurOnly' => $eurOnly,
        ];
    };

    $hi = -1;
    foreach ($rows as $i => $r) {
        if ($isHeader($r)) { $hi = $i; break; }
    }
    // Имя листа, а не только счётчик: «листов без заголовка: 6» не говорит,
    // потеряли мы служебную страницу или четыреста позиций.
    if ($hi < 0) { $skipped++; $skippedNames[] = $s['name']; continue; }

    $map = $mapCols($rows, $hi);
    if (!$map) { $skipped++; $skippedNames[] = $s['name'] . ' (нет колонки цены)'; continue; }
    $before = count($items);

    $section = '';
    $lastName = '';   // последнее осмысленное наименование листа — для строк-продолжений
    $n = count($rows);
    for ($i = $hi + 1; $i < $n; $i++) {
        $r = $rows[$i];

        /**
         * Шапок на листе бывает несколько, и раскладка у них разная.
         *
         * «STOUT Арматура» — четыре таблицы. Первые три: «Артикул | Размер |
         * Кол-во | Цена EUR | Цена РУБ». Четвёртая, с 38-й строки: «Наименование |
         * Артикул | Т воды | Рраб | Размер | Упаковка | Цена EUR» — колонки
         * сдвинуты, рублёвой цены нет совсем. Раскладка первой таблицы
         * применялась ко всему листу: там, где ожидалась цена, лежал размер
         * («3/4"»), строка признавалась заголовком раздела и молча
         * выбрасывалась. Так пропал весь блок с фильтрами сетчатыми,
         * кранами шаровыми мини и обратными клапанами — включая
         * SFW-0001-000020, который в прайсе есть.
         *
         * Поэтому шапку перечитываем каждый раз, когда она встречается.
         */
        if ($isHeader($r)) {
            $m2 = $mapCols($rows, $i);
            /**
             * Новая таблица — новый контекст: наследовать наименование блока
             * из предыдущей нельзя, там другой товар.
             *
             * Пробовал сохранять заголовок раздела, стоящий прямо перед
             * шапкой («Energoflex Super Protect»), — и отказался: вместе с
             * пользой на четырёх листах это подставило мусор на двух других.
             * У радиаторов ROMMER заголовком оказывалась строка «· соответствует
             * ГОСТ 31311-2005», у насосов STOUT — «Принадлежности», и они
             * вытесняли осмысленное имя листа. Разбирать, где заголовок
             * настоящий, а где обрывок описания, здесь нечем.
             */
            if ($m2) { $map = $m2; $section = ''; $lastName = ''; }
            continue;
        }

        $cPrice = $map['price'];
        $cArt   = $map['art'];
        $cName  = $map['name'];
        $cSize  = $map['size'];

        $price = $r[$cPrice] ?? null;
        $art = $canonize($r[$cArt] ?? '');
        if ($art === '' && ($map['art2'] ?? null) !== null) $art = $canonize($r[$map['art2']] ?? '');

        /**
         * Курс евро берём из самой книги, а не из настроек.
         *
         * Там, где есть обе цены, их отношение и есть курс: 917,40 ₽ / 8,34 € =
         * 110. Считать его по строкам надёжнее, чем ссылаться на ячейку
         * «Оглавление!B14»: адрес в книге меняется, а отношение цен — нет.
         */
        // Колонка евро и колонка цены — одна и та же (лист с рублями под
        // подписью EURO): делить её на саму себя нельзя, курс вышел бы 1.
        if (!$map['eurOnly'] && $map['eur'] !== null && $map['eur'] !== $map['price']
            && is_numeric($price)) {
            $e = $r[$map['eur']] ?? null;
            if (is_numeric($e) && (float)$e > 0 && (float)$price > 0) {
                $eurRates[] = (float)$price / (float)$e;
            }
        }

        if (!is_numeric($price)) {
            // Заголовок раздела: короткая строка без двоеточий и техописаний.
            $first = trim((string)($r[$cArt] ?? ($r['A'] ?? ($r['B'] ?? ''))));
            $clean = trim(preg_replace('/\s+/u', ' ', $first));
            if ($clean !== '' && mb_strlen($clean) > 3 && mb_strlen($clean) < 80
                && !preg_match('/[:;]\s*$/u', $clean)
                // Код товара заголовком раздела быть не может. На «Энергофлексе»
                // строка без цены несёт артикул соседнего блока, и он становился
                // «разделом», после чего лез в название каждой позиции листа.
                && !preg_match('/^[A-Za-z0-9.\-]{8,}$/', $clean)
                && !preg_match('/^артикул|информац|внимание|примечан|условия|доставк/ui', $clean)) {
                $section = $clean;
            }
            continue;
        }
        // Позиция без артикула — всё равно позиция: подбор умеет искать по
        // названию, и «Лён сантехнический коса 200 г» полезен в смете даже
        // без кода. Раньше такие строки выбрасывались целиком.
        $name = $cName ? trim((string)($r[$cName] ?? '')) : '';
        // Название собрано не из собственной ячейки, а унаследовано у блока —
        // такое в $lastName не записываем, иначе размеры накапливались бы:
        // «…x10», потом «…x10 x11», потом «…x10 x11 x12».
        $inherited = false;
        if ($name === '') {
            $size = $cSize ? trim((string)($r[$cSize] ?? '')) : '';
            /**
             * Наследуем наименование БЛОКА, а не заголовок раздела.
             *
             * Серия коллекторов ROMMER лежит в прайсе блоками по одиннадцать
             * строк: наименование стоит в первой, остальные несут только размер.
             * Заголовок же раздела один на весь лист — «Коллекторы из
             * нержавеющей стали». Пока подставлялся он, RMS-1200-000010 (с
             * расходомерами) и RMS-1210-000010 (полностью укомплектован)
             * получали одно и то же название и различить их было нечем: подбор
             * по счёту брал любой из них.
             */
            if ($size !== '') {
                $base = $lastName !== '' ? $blockHead($lastName) : $section;
                $name = trim($base . ' ' . $size);
                if ($name !== '') $inherited = true;
            } else {
                /**
                 * Отличить строку от соседних нечем — наследовать нельзя.
                 *
                 * В листе «Энергофлекс» колонки размера нет вовсе, и на одном
                 * унаследованном наименовании вся серия трубок получила бы
                 * размер первой строки: «15/4-11 синий» и у 18-й, и у 22-й.
                 * Оставляем строку пустой — ниже название соберётся из
                 * соседних колонок, где размер как раз и написан.
                 */
                $name = $section;
            }
        }
        /**
         * Если названия нет или в нём оказался сам артикул — собираем его из
         * соседних колонок строки.
         *
         * Так устроен лист «Энергофлекс»: колонки идут «18 | 18/4-11 | синий |
         * EFXT0180411SUPRS | цена», и колонки «наименование» там нет вовсе.
         * В индекс попадал артикул вместо названия, и найти такую позицию по
         * названию было нечем — при том что в смете её пишут словами.
         */
        /**
         * Берём ячейки ТОЛЬКО СВОЕГО блока — те, что стоят слева от артикула.
         *
         * На «Энергофлексе» в одной строке лежат сразу несколько исполнений:
         * «15 | 15/4-11 | синий | EFXT0150411SUPRS | цена | цена | 15/6-2 |
         * синий | EFXT015062SUPRS-440 | цена». Прежний обход брал ячейки всей
         * строки подряд, и обе позиции получали одно название на двоих —
         * «15/4-11 синий 15/6-2 синий», а вторая ещё и с чужим артикулом
         * внутри. Ни найти по названию, ни отличить одну от другой.
         *
         * Своё описание изделия стоит непосредственно перед его кодом, поэтому
         * идём от артикула ВЛЕВО и останавливаемся, наткнувшись на чужой код
         * или на пустую ячейку-разделитель.
         */
        /**
         * Название, которое само оказалось чужим кодом, — тоже не название.
         *
         * На «Энергофлексе» в колонке названия второго блока лежит артикул
         * СОСЕДНЕЙ позиции: «EFXT018092SUPRK-284» у всех строк подряд. Условие
         * «пусто или равно своему артикулу» такое не ловило.
         */
        $nameIsCode = $name !== '' && preg_match('/^[A-Za-z0-9.\-]{8,}$/', $name);

        if ($name === '' || $name === $art || $nameIsCode) {
            // Один проход слева направо, храним три последние подходящие
            // ячейки перед кодом. Сортировать колонки не нужно: разбор листа
            // складывает их в порядке появления, то есть уже слева направо.
            $artNo = colNum($cArt);
            $mine = [];
            foreach ($r as $col => $v) {
                if (colNum($col) >= $artNo) break;      // дальше идёт чужой блок
                $t = $squash($v);
                if ($t === '' || $t === $art) { $mine = []; continue; }   // пустая ячейка разделяет блоки
                // Чужой артикул: латиница с цифрами длиннее восьми знаков.
                if (preg_match('/^[A-Za-z0-9.\-]{8,}$/', $t) || mb_strlen($t) > 60) { $mine = []; continue; }
                $mine[] = $t;
                if (count($mine) > 3) array_shift($mine);
            }
            /**
             * Цветное исполнение стоит строкой ниже, а размер — только у первого.
             *
             * На «Энергофлексе» пара исполнений записана двумя строками:
             *   «22 | 22/4-11 | синий  | EFXT0220411SUPRS | цена»
             *   «   |          | красный| EFXT0220411SUPRK | цена»
             * У красной размер не повторяют, и своего блока ей хватает ровно на
             * слово «красный». В индексе она так и лежала — «красный», без
             * диаметра и без предмета, — и «Теплоизоляция Энергофлекс Super
             * Protect 22мм красная» из счёта не находила её вовсе, хотя синяя
             * того же ряда находилась.
             *
             * Цвет — никогда не название товара, поэтому в таком случае (и
             * только в таком) пустые ячейки своего блока берём из строки выше:
             * там стоит размер этой же пары.
             */
            if ($i > $hi + 1 &&
                preg_match('/^(красн|син|бел|чёрн|черн|сер)[а-яё]*$/ui', trim(implode(' ', $mine)))) {
                $prev = $rows[$i - 1];
                $cols = array_unique(array_merge(array_keys($r), array_keys($prev)));
                usort($cols, function ($x, $y) { return colNum($x) - colNum($y); });
                $filled = [];
                foreach ($cols as $col) {
                    if (colNum($col) >= $artNo) break;
                    $t = $squash($r[$col] ?? '');
                    if ($t === '') $t = $squash($prev[$col] ?? '');
                    if ($t === '' || $t === $art) { $filled = []; continue; }
                    if (preg_match('/^[A-Za-z0-9.\-]{8,}$/', $t) || mb_strlen($t) > 60) { $filled = []; continue; }
                    $filled[] = $t;
                    if (count($filled) > 3) array_shift($filled);
                }
                if (count($filled) > count($mine)) $mine = $filled;
            }
            $built = trim($section . ' ' . implode(' ', $mine));
            if (mb_strlen($built) >= 3) { $name = $built; $inherited = false; }
        }
        if ($name === '') $name = $section !== '' ? $section : $art;
        $name = $squash($name);

        /**
         * Название из одних цифр — это продолжение объединённой ячейки.
         *
         * Наименование в таких листах написано один раз на весь блок, а в
         * строках ниже остаётся только размер или вовсе посторонний номер:
         * «8207», «100», «5321 415». Пятнадцать процентов прайса выглядели
         * именно так, и найти подобную позицию по названию было нечем — а
         * распознавание счёта ищет прежде всего по словам.
         *
         * Берём последнее осмысленное название этого листа и оставляем цифры
         * как уточнение: они и есть отличие строки от соседних, без них
         * позиции блока стали бы неразличимы.
         */
        // Ни одной буквы — значит это не название, а остаток строки-продолжения:
        // «8207», «100», «5321 415», а в блочных таблицах ещё и голый размер
        // «3/4"» или «1 1/4"». Прежняя проверка ловила только цифры и пропускала
        // размеры с дробью и кавычкой — позиция уходила в индекс без названия.
        /**
         * Название, состоящее из одного артикула, — тоже не название.
         *
         * В «STOUT Радиаторах отопления» колонка наименования заполнена кодами:
         * у строки SRB-0310-050006 там написано «SRB-0310-050005». Такое нельзя
         * ни оставлять названием, ни тем более запоминать как образец блока:
         * весь блок унаследовал бы чужой код вместо наименования.
         */
        $codeOnly = preg_match($reCanon, $name, $cm2)
            && mb_strlen(trim(str_replace($cm2[1], '', $name))) < 3;

        if (!preg_match('/\p{L}/u', $name) || $codeOnly) {
            // Последний запасной вариант — имя листа: в «Rommer Конвекторы
            // внутрипольные» и «STOUT Радиаторы отопления» осмысленного
            // наименования нет ни в одной строке вообще, только числа.
            $base = $lastName !== '' ? $blockHead($lastName) : ($section !== '' ? $section : $s['name']);
            if ($base !== '') { $name = trim($base . ' ' . $name); $inherited = true; }
        } elseif (!$inherited && mb_strlen($name) > 3) {
            // Запоминаем только СОБСТВЕННОЕ наименование строки. Унаследованное
            // писать сюда нельзя: следующая строка блока унаследовала бы его
            // вместе с чужим размером.
            $lastName = $name;
        }
        if (mb_strlen($name) < 3) continue;

        /**
         * Артикул, спрятанный в названии.
         *
         * В листах «ROMMER Дымоходы», «STOUT бойлеры комб и кос», «Rommer
         * Трубопроводная арматура» колонка артикула заполнена порядковым
         * номером («27647»), а настоящий код стоит в начале наименования:
         * «RCA-6010-751000 ROMMER Комплект дымохода традиц. …». По номеру
         * строки не найти ни картинку, ни позицию при распознавании счёта —
         * поэтому код забираем из названия, а из названия убираем: там он
         * только мешает поиску по словам.
         */
        if (!preg_match($reCanon, $art) && preg_match($reCanon, $name, $am)) {
            $art = $am[1];
            $stripped = trim(preg_replace('/\s{2,}/u', ' ', str_replace($am[1], '', $name)));
            if (mb_strlen($stripped) >= 3) $name = $stripped;
        }

        $p = round((float)$price, 2);
        if ($p <= 0) continue;

        /**
         * Висячие дефисы в артикуле.
         *
         * В листах «BAXI котлы» и «De Dietrich» код записан с хвостом:
         * «7671757--», «CZB46124352-», «6241010197-». Всего таких 99 позиций.
         * Артикул печатается клиенту в смете и по нему ищется фото товара в
         * img/, поэтому мусорный хвост — не косметика. Дефисы ВНУТРИ кода
         * (SWH-1110-000300) обязаны остаться, обрезаем только по краям.
         */
        $art = trim($art, " \t-–—");

        $items[] = ['a' => utf8Clean($art), 'n' => utf8Clean(mb_substr($name, 0, 110)),
            'p' => $p, 's' => utf8Clean($s['name'])];
        if ($map['eurOnly']) $eurIdx[] = count($items) - 1;
    }
    if (count($items) === $before) $emptySheets[] = $s['name'];
    unset($rows);
}

$zip->close();
