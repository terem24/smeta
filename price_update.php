/** Номер колонки по её имени: A → 1, Z → 26, AA → 27. */
function colNum($col) {
    $n = 0;
    foreach (str_split(strtoupper((string)$col)) as $ch) {
        if ($ch < 'A' || $ch > 'Z') continue;
        $n = $n * 26 + (ord($ch) - 64);
    }
    return $n;
}

/**
 * Ячейка, обрезанная посреди русской буквы.
 *
 * В прайсе такое встречается: на листе «БЕЛАМОС» два артикула кончаются
 * половиной многобайтового символа. Само по себе это мелочь, но json_encode
 * на первой же такой строке возвращает false — и индекс записывался ПУСТЫМ
 * файлом, то есть обвалился бы весь подбор по прайсу разом.
 *
 * Битый хвост отрезаем, остальное оставляем как есть.
 */
function utf8Clean($s) {
    $s = (string)$s;
    if ($s === '' || mb_check_encoding($s, 'UTF-8')) return $s;
    $fixed = @iconv('UTF-8', 'UTF-8//IGNORE', $s);
    return $fixed === false ? preg_replace('/[\x80-\xFF]/', '', $s) : $fixed;
}

