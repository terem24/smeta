    ['version' => $version, 'built' => date('Y-m-d'), 'source' => $stamp, 'items' => $uniq],
    JSON_UNESCAPED_UNICODE
);

/**
 * Пустой индекс не пишем никогда.
 *
 * json_encode возвращает false на первой же битой строке, и прежний код
 * записывал этот false как пустой файл поверх рабочего индекса: подбор по
 * прайсу отвалился бы целиком, а причина осталась бы в логе, который никто
 * не читает. Лучше оставить старый индекс и упасть с внятным сообщением.
 */
if ($json === false || strlen($json) < 100000) {
    fail('индекс не собран: ' . ($json === false
        ? 'json_encode — ' . json_last_error_msg()
        : 'получилось всего ' . strlen($json) . ' байт. Прежний индекс не тронут'));
}

