function httpGet($url, $toFile = null) {
    $ch = curl_init($url);
    curl_setopt($ch, CURLOPT_FOLLOWLOCATION, true);
    curl_setopt($ch, CURLOPT_TIMEOUT, 900);
    curl_setopt($ch, CURLOPT_USERAGENT, 'Mozilla/5.0 HeatCalc price updater');
    curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, true);
    curl_setopt($ch, CURLOPT_SSL_VERIFYHOST, 2);

    if ($toFile) {
        $fp = fopen($toFile, 'wb');
        if (!$fp) fail("не открыть файл для записи: $toFile");
        curl_setopt($ch, CURLOPT_FILE, $fp);
        $ok = curl_exec($ch);
        $err = curl_error($ch);
        curl_close($ch);
        fclose($fp);
        if (!$ok) fail("скачивание не удалось: $err");
        return filesize($toFile);
    }

    curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
    $body = curl_exec($ch);
    $err = curl_error($ch);
    curl_close($ch);
    if ($body === false) fail("страница не открылась: $err");
    return $body;
}

/**
 * Дата и размер файла на сервере ТЕРЕМ — без скачивания (запрос HEAD).
 * Пустая строка, если сервер их не сообщил: тогда решаем по подписи месяца.
 */
function httpStamp($url) {
    $ch = curl_init($url);
    curl_setopt($ch, CURLOPT_NOBODY, true);
    curl_setopt($ch, CURLOPT_FOLLOWLOCATION, true);
    curl_setopt($ch, CURLOPT_TIMEOUT, 60);
    curl_setopt($ch, CURLOPT_USERAGENT, 'Mozilla/5.0 HeatCalc price updater');
    curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
    curl_setopt($ch, CURLOPT_FILETIME, true);
    $ok = curl_exec($ch);
    $time = curl_getinfo($ch, CURLINFO_FILETIME);
    $size = curl_getinfo($ch, CURLINFO_CONTENT_LENGTH_DOWNLOAD);
    curl_close($ch);
    if ($ok === false || $time <= 0) return '';
    return gmdate('Y-m-d H:i:s', $time) . ' / ' . ($size > 0 ? (int)$size : '?');
}

