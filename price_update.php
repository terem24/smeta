/** Разбор одного листа в массив строк вида [колонка => значение]. */
function parseSheet($xmlStr, $shared, $sheetName = '') {
    $rows = [];
    if (preg_match_all('/<row[^>]*>(.*?)<\/row>/s', $xmlStr, $rm) === false) {
        // Явно сообщаем о срыве разбора: тихо потерянный лист — худший исход.
        // preg_last_error_msg() есть только с PHP 8 — на 7.x берём код.
        $why = function_exists('preg_last_error_msg')
            ? preg_last_error_msg()
            : ('код ошибки PCRE ' . preg_last_error());
        logmsg('лист «' . $sheetName . '» не разобран: ' . $why);
        return [];
    }
    foreach ($rm[1] as $r) {
        /**
         * Пустая ячейка записана самозакрывающимся тегом: <c r="A56" s="7700"/>.
         *
         * Прежний шаблон «<c ...>(.*?)</c>» такой тег принимал за ОТКРЫВАЮЩИЙ —
         * `[^>]*` останавливался на `>` внутри `/>`, — и подтягивал в него
         * содержимое СЛЕДУЮЩЕЙ ячейки, вместе с её колонкой теряя и признак
         * t="s". Значение уходило не в ту колонку и не расшифровывалось: вместо
         * артикула «SFW-0001-000020» в колонку A попадал номер общей строки
         * «3998». Отсюда же артикулы-числа вроде «6810», под которые в разборе
         * потом городились проверки колонки по данным.
         *
         * Поэтому самозакрывающийся тег разбираем отдельной веткой.
         */
        preg_match_all('/<c r="([A-Z]+)\d+"([^>]*?)(?:\/>|>(.*?)<\/c>)/s', $r, $cm, PREG_SET_ORDER);
        $cells = [];
        foreach ($cm as $c) {
            if (!preg_match('/<v>(.*?)<\/v>/s', $c[3] ?? '', $vm)) continue;
            $v = $vm[1];
            $cells[$c[1]] = (strpos($c[2], 't="s"') !== false)
                ? ($shared[(int)$v] ?? '')
                : $v;
        }
        if ($cells) $rows[] = $cells;
    }
    return $rows;
}

